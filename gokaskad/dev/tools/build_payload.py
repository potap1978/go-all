#!/usr/bin/env python3
"""Embed lib/kaskad/**/*.py into install.sh (docs/k3/SPEC-wave1.md, 5.2).

The code travels inside the single-file program as a deterministic tar.gz:

    * only ``*.py`` and ``*.json`` (data such as vendor/clients.json) under ``lib/kaskad``, plus the
      static files of the web panel under ``lib/kaskad/panel/static`` (html, js, css, svg, txt, woff2, png)
      and the patches under ``lib/kaskad/vendor`` (``*.patch``: the build fix of the AmneziaWG kernel
      module, gw/awgkmod.py) and the agent guide ``lib/kaskad/mcp/*.md`` (the resource kaskad://guide of
      kaskad-mcp) and the texts of the SSH menu ``lib/kaskad/i18n/sh/*.sh`` (no ``__pycache__``, no dot files),
      names sorted; the translation catalogs ``lib/kaskad/i18n/catalog/<lang>/*.json`` ride as data (*.json) and
      must be complete (i18n_problems),
      stored as ``kaskad/...``;
    * tar: ustar, mtime 0, uid/gid 0, empty owner names, mode 0644, regular files only;
    * gzip: mtime 0, no file name, level 9;
    * base64, 76 characters per line.

The texts of the SSH menu and the installer (``lib/kaskad/i18n/sh/<area>.ru.sh`` and ``<area>.en.sh``: one line
``M_<lang>_<KEY>='text'`` each) travel in the payload too (``kaskad/i18n/sh/*.sh``) and are written verbatim,
without comments, between the marker lines ``# >>> K3_I18N …`` and ``# <<< K3_I18N`` near the top of install.sh:
the single file has them from its first screen (bash <(curl …), curl … | bash), before the payload is unpacked.
Both languages of an area must hold the same keys, a key lives in one area only, and the printf placeholders
(%s, %d, …) of a key must be the same in both languages. After the texts the block holds ``K3_HOST_URL_<ID>='…'``
— the addresses of the partner hosting from ``lib/kaskad/setup/product.py`` (HOSTING, their one place; the texts
take them by %s).

The payload is written between the marker lines of install.sh::

    # >>> K3_PAYLOAD (generated by tools/build_payload.py, do not edit)
    K3_LIB_SHA="<sha256 of the tar.gz>"
    k3_payload() {
        cat <<'K3PAYLOAD'
    ...base64...
    K3PAYLOAD
    }
    # <<< K3_PAYLOAD

``install.sh`` (k3_ensure_lib) decodes it, checks the sha256 and unpacks it to
``/opt/kaskad/lib/<sha12>``.

Usage:
    python3 tools/build_payload.py            rebuild the block in install.sh
    python3 tools/build_payload.py --check    exit 1 if the block is missing, corrupted or does
                                              not hold exactly the current lib/kaskad sources
    python3 tools/build_payload.py --check --clean
                                              the same, and also exit 1 if git sees changed or new files under
                                              lib/kaskad or install.sh (the check of a release: a payload built
                                              from a dirty tree once shipped a scratch file, REV-it1-b С-2)
Options: --script PATH (default install.sh), --lib PATH (default lib).

Scratch files of the panel (names starting with ``__`` under lib/kaskad/panel/static: seeds and probes of the
checks) are never packed: build and --check refuse with an error naming them — move them out (scratchpad).
"""

import argparse
import base64
import gzip
import hashlib
import io
import os
import re
import sys
import tarfile
import tempfile

BEGIN = "# >>> K3_PAYLOAD (generated by tools/build_payload.py, do not edit)"
END = "# <<< K3_PAYLOAD"
HEREDOC = "K3PAYLOAD"
I18N_BEGIN = "# >>> K3_I18N (generated by tools/build_payload.py from lib/kaskad/i18n/sh/*.sh, do not edit)"
I18N_END = "# <<< K3_I18N"
I18N_LANGS = ("ru", "en")
# Текст — в одинарных кавычках; одинарная кавычка внутри — '\'' (закрыть, кавычка через \, открыть): can'\''t.
_I18N_LINE = re.compile(r"^M_(ru|en)_([A-Za-z0-9_]+)='((?:[^']|'\\'')*)'$")
# Подстановки printf (для tf): %s, %d, %5s, %-3d, %%… Флаг «пробел» не берём: «60% off» — текст, а не подстановка.
_PRINTF = re.compile(r"%(?:%|[-+0#]*[0-9*]*(?:\.[0-9*]+)?[sdiouxXfFeEgGcbq])")
WIDTH = 76

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


STATIC_EXT = (".html", ".js", ".css", ".svg", ".txt", ".woff2", ".png")   # lib/kaskad/panel/static only (png — icons of apps)


class ScratchFiles(SystemExit):
    """Scratch files (``__*``) in lib/kaskad/panel/static — the payload would ship them to every server."""


def collect(lib_dir):
    """[(archive name, bytes)] of every lib/kaskad/**/*.py and *.json (and the files of
    lib/kaskad/panel/static: html, js, css, svg, txt, woff2, png; lib/kaskad/vendor/*.patch; lib/kaskad/mcp/*.md), sorted
    by name."""
    base = os.path.join(lib_dir, "kaskad")
    if not os.path.isdir(base):
        raise SystemExit("нет каталога %s" % base)
    out, scratch = [], []
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d != "__pycache__" and not d.startswith("."))
        static = os.sep + os.path.join("panel", "static") in dirpath   # the web panel ships its files too
        vendor = os.path.basename(dirpath) == "vendor"                  # patches of vendored sources
        mcp = os.path.basename(dirpath) == "mcp"                        # the agent guide of the MCP server
        shcat = dirpath.endswith(os.sep + os.path.join("i18n", "sh"))   # texts of the SSH menu (K3_I18N)
        for fn in filenames:
            if static and fn.startswith("__"):
                scratch.append(os.path.relpath(os.path.join(dirpath, fn), lib_dir).replace(os.sep, "/"))
                continue
            if fn.startswith(".") or not (fn.endswith((".py", ".json"))
                                          or (static and fn.endswith(STATIC_EXT))
                                          or (vendor and fn.endswith(".patch"))
                                          or (mcp and fn.endswith(".md"))
                                          or (shcat and fn.endswith(".sh"))):
                continue
            full = os.path.join(dirpath, fn)
            name = os.path.relpath(full, lib_dir).replace(os.sep, "/")
            with open(full, "rb") as f:
                out.append((name, f.read()))
    if scratch:
        raise ScratchFiles("в панели служебные файлы (%s) — в install.sh им не место: уберите их из lib/kaskad/panel/static "
                           "(сиды и пробы — в scratchpad) и повторите" % ", ".join(sorted(scratch)))
    out.sort(key=lambda x: x[0])
    return out


def build_archive(files):
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.USTAR_FORMAT) as tf:
        for name, data in files:
            ti = tarfile.TarInfo(name)
            ti.size = len(data)
            ti.mtime = 0
            ti.mode = 0o644
            ti.uid = ti.gid = 0
            ti.uname = ti.gname = ""
            ti.type = tarfile.REGTYPE
            tf.addfile(ti, io.BytesIO(data))
    gz = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=gz, compresslevel=9, mtime=0) as g:
        g.write(raw.getvalue())
    return gz.getvalue()


def render_block(archive):
    sha = hashlib.sha256(archive).hexdigest()
    b64 = base64.b64encode(archive).decode("ascii")
    lines = [b64[i:i + WIDTH] for i in range(0, len(b64), WIDTH)]
    return [BEGIN, 'K3_LIB_SHA="%s"' % sha, "k3_payload() {", "    cat <<'%s'" % HEREDOC] \
        + lines + [HEREDOC, "}", END]


def find_block(lines):
    """(start, end) indexes of the marker lines (inclusive) or raise SystemExit."""
    starts = [i for i, l in enumerate(lines) if l == BEGIN]
    ends = [i for i, l in enumerate(lines) if l == END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] <= starts[0]:
        raise SystemExit("в install.sh нет пары строк-меток K3_PAYLOAD (или их несколько)")
    return starts[0], ends[0]


def parse_block(block):
    """(sha, archive bytes) from the lines between the markers, or raise ValueError."""
    if len(block) < 7 or block[0] != BEGIN or block[-1] != END:
        raise ValueError("блок пуст или повреждён")
    m = re.match(r'^K3_LIB_SHA="([0-9a-f]{64})"$', block[1])
    if not m or block[2] != "k3_payload() {" or block[3] != "    cat <<'%s'" % HEREDOC \
            or block[-3] != HEREDOC or block[-2] != "}":
        raise ValueError("блок не в том формате")
    body = block[4:-3]
    if not body or any(not re.match(r"^[A-Za-z0-9+/=]{1,%d}$" % WIDTH, l) for l in body):
        raise ValueError("в base64 посторонние символы")
    archive = base64.b64decode("".join(body))
    if hashlib.sha256(archive).hexdigest() != m.group(1):
        raise ValueError("sha256 архива не совпадает с K3_LIB_SHA")
    return m.group(1), archive


def archive_files(archive):
    out = []
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as tf:
        for ti in tf.getmembers():
            if not ti.isfile():
                raise ValueError("в архиве не файл: %s" % ti.name)
            out.append((ti.name, tf.extractfile(ti).read()))
    return sorted(out, key=lambda x: x[0])


def i18n_entries(lib_dir):
    """[(area, {lang: [(key, text, line)]})] from lib/kaskad/i18n/sh/<area>.<lang>.sh, areas sorted, checked: the
    format of every line, a key once in all the areas, the same keys in every language of an area, the same printf
    placeholders in every language. Raise SystemExit on errors."""
    d = os.path.join(lib_dir, "kaskad", "i18n", "sh")
    if not os.path.isdir(d):
        raise SystemExit("нет каталога %s" % d)
    names = sorted(fn for fn in os.listdir(d) if fn.endswith(".sh") and not fn.startswith("."))
    areas = sorted(set(fn.rsplit(".", 2)[0] for fn in names if fn.count(".") == 2))
    out, errs, owner = [], [], {}
    for fn in names:
        if fn.count(".") != 2 or fn.split(".")[1] not in I18N_LANGS:
            errs.append("%s: имя не <область>.<%s>.sh" % (fn, "|".join(I18N_LANGS)))
    for area in areas:
        langs = {}
        for lang in I18N_LANGS:
            fn = "%s.%s.sh" % (area, lang)
            path = os.path.join(d, fn)
            rows, seen = [], set()
            if not os.path.isfile(path):
                errs.append("нет файла %s" % fn)
            else:
                with open(path, "r", encoding="utf-8", newline="") as f:
                    for n, line in enumerate(f.read().split("\n"), 1):
                        if not line.strip() or line.lstrip().startswith("#"):
                            continue
                        m = _I18N_LINE.match(line)
                        if not m or m.group(1) != lang:
                            errs.append("%s:%d: не строка M_%s_<КЛЮЧ>='текст'" % (fn, n, lang))
                            continue
                        k = m.group(2)
                        if k in seen:
                            errs.append("%s:%d: ключ %s повторяется" % (fn, n, k))
                            continue
                        if owner.setdefault((lang, k), area) != area:
                            errs.append("%s:%d: ключ %s уже есть в области %s" % (fn, n, k, owner[(lang, k)]))
                            continue
                        seen.add(k)
                        rows.append((k, m.group(3), line))
            langs[lang] = rows
        keys = {lang: dict((k, v) for k, v, _l in rows) for lang, rows in langs.items()}
        for lang in I18N_LANGS[1:]:
            for k in sorted(set(keys["ru"]) - set(keys[lang])):
                errs.append("%s.%s.sh: нет ключа %s" % (area, lang, k))
            for k in sorted(set(keys[lang]) - set(keys["ru"])):
                errs.append("%s.%s.sh: лишний ключ %s (его нет в %s.ru.sh)" % (area, lang, k, area))
            for k in sorted(set(keys["ru"]) & set(keys[lang])):
                a, b = _PRINTF.findall(keys["ru"][k]), _PRINTF.findall(keys[lang][k])
                if a != b:
                    errs.append("%s: ключ %s: подстановки printf разные (ru %s, %s %s)" % (area, k, a, lang, b))
        out.append((area, langs))
    if errs:
        raise SystemExit("тексты SSH (lib/kaskad/i18n/sh/*.sh):\n  " + "\n  ".join(errs))
    return out


_HOST_URL = re.compile(r"^https://[A-Za-z0-9.-]+(/[A-Za-z0-9._~/?=&%-]*)?$")


def hosting_lines(lib_dir):
    """``K3_HOST_URL_<ID>='https://…'`` for every partner hosting of lib/kaskad/setup/product.py (HOSTING — the one
    place of these addresses; the SSH texts take them by %s). Read as data (ast), not imported. No file — none."""
    import ast
    path = os.path.join(lib_dir, "kaskad", "setup", "product.py")
    if not os.path.isfile(path):
        return []
    with open(path, "r", encoding="utf-8") as f:
        tree = ast.parse(f.read(), path)
    rows = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "HOSTING" for t in node.targets):
            rows = ast.literal_eval(node.value)
    if rows is None:
        raise SystemExit("%s: нет HOSTING" % path)
    out = []
    for r in rows:
        if not re.match(r"^[a-z0-9]+$", r.get("id") or "") or not _HOST_URL.match(r.get("url") or ""):
            raise SystemExit("%s: HOSTING: плохая запись %r" % (path, r))
        out.append("K3_HOST_URL_%s='%s'" % (r["id"].upper(), r["url"]))
    return out


def render_i18n(lib_dir):
    body = []
    for _area, langs in i18n_entries(lib_dir):
        for lang in I18N_LANGS:
            body += [line for _k, _v, line in langs[lang]]
    return [I18N_BEGIN] + body + hosting_lines(lib_dir) + [I18N_END]


def find_i18n(lines):
    starts = [i for i, l in enumerate(lines) if l == I18N_BEGIN]
    ends = [i for i, l in enumerate(lines) if l == I18N_END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] <= starts[0]:
        raise SystemExit("в install.sh нет пары строк-меток K3_I18N (или их несколько)")
    return starts[0], ends[0]


def read_lines(path):
    with open(path, "r", encoding="utf-8", newline="") as f:
        text = f.read()
    return text.split("\n")


def write_atomic(path, text):
    d = os.path.dirname(os.path.abspath(path))
    mode = os.stat(path).st_mode & 0o7777
    fd, tmp = tempfile.mkstemp(prefix=".install.", dir=d)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def i18n_problems(lib_dir):
    """Problems of the Python translation catalogs lib/kaskad/i18n/catalog/<lang>/*.json (kaskad.i18n.check: ru == en
    keys, the same placeholders, no Russian in English) — the payload is not built or accepted with them."""
    cat = os.path.join(lib_dir, "kaskad", "i18n", "catalog")
    if not os.path.isdir(cat):
        return []
    sys.path.insert(0, os.path.abspath(lib_dir))
    try:
        from kaskad.i18n import check as i18n_check
    finally:
        sys.path.pop(0)
    return i18n_check.catalog_problems(catalog_dir=cat)


def _i18n_ok(lib_dir):
    probs = i18n_problems(lib_dir)
    for p in probs:
        print("каталог перевода: %s" % p)
    return not probs


def dirty(paths):
    """Changed, new or deleted files git sees under paths ([] — clean; None — not a git tree)."""
    import subprocess
    try:
        r = subprocess.run(["git", "status", "--porcelain", "--untracked-files=all", "--"] + list(paths), cwd=ROOT,
                           stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return None
    if r.returncode:
        return None
    return [ln[3:] for ln in r.stdout.decode("utf-8", "replace").splitlines() if ln.strip()]


def check(script, lib_dir, clean=False):
    if clean:
        left = dirty([os.path.relpath(lib_dir, ROOT), os.path.relpath(script, ROOT)])
        if left is None:
            print("K3_PAYLOAD: --clean — не git-дерево, чистоту не проверить")
            return 1
        if left:
            print("K3_PAYLOAD: дерево не чистое (%s) — проверка выпуска только на чистом дереве: закоммитьте или уберите"
                  % ", ".join(left[:10] + (["…"] if len(left) > 10 else [])))
            return 1
    if not _i18n_ok(lib_dir):
        return 1
    current = collect(lib_dir)                         # первым: служебные файлы панели — отказ раньше разбора блока
    lines = read_lines(script)
    s, e = find_block(lines)
    try:
        sha, archive = parse_block(lines[s:e + 1])
        embedded = archive_files(archive)
    except ValueError as err:
        print("K3_PAYLOAD: %s — пересоберите: python3 tools/build_payload.py" % err)
        return 1
    if embedded != current:
        have = dict(embedded)
        want = dict(current)
        diff = sorted(n for n in set(have) | set(want) if have.get(n) != want.get(n))
        print("K3_PAYLOAD устарел (%s) — пересоберите: python3 tools/build_payload.py" % ", ".join(diff))
        return 1
    print("K3_PAYLOAD актуален: %d файлов, sha256 %s" % (len(current), sha[:12]))
    s, e = find_i18n(lines)
    want = render_i18n(lib_dir)
    if lines[s:e + 1] != want:
        print("K3_I18N устарел (тексты lib/kaskad/i18n/sh/*.sh) — пересоберите: python3 tools/build_payload.py")
        return 1
    n = len(want) - 2 - len(hosting_lines(lib_dir))
    print("K3_I18N актуален: %d ключей на язык (%s)" % (n // len(I18N_LANGS), ", ".join(I18N_LANGS)))
    return 0


def build(script, lib_dir):
    if not _i18n_ok(lib_dir):
        return 1
    files = collect(lib_dir)                           # первым: служебные файлы панели — отказ до записи
    lines = read_lines(script)
    s, e = find_block(lines)
    block = render_block(build_archive(files))
    new = lines[:s] + block + lines[e + 1:]
    i18n = render_i18n(lib_dir)
    s2, e2 = find_i18n(new)
    new = new[:s2] + i18n + new[e2 + 1:]
    if new != lines:
        write_atomic(script, "\n".join(new))
    sha = block[1].split('"')[1]
    print("K3_PAYLOAD: %d файлов, sha256 %s, %d строк base64" % (len(files), sha[:12], len(block) - 7))
    n = len(i18n) - 2 - len(hosting_lines(lib_dir))
    print("K3_I18N: %d ключей на язык (%s)" % (n // len(I18N_LANGS), ", ".join(I18N_LANGS)))
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="встроить lib/kaskad в install.sh")
    ap.add_argument("--check", action="store_true", help="только проверить, что блок актуален")
    ap.add_argument("--clean", action="store_true", help="с --check: ещё и дерево git чистое (lib, install.sh) — проверка выпуска")
    ap.add_argument("--script", default=os.path.join(ROOT, "install.sh"))
    ap.add_argument("--lib", default=os.path.join(ROOT, "lib"))
    a = ap.parse_args(argv)
    try:
        if a.check:
            return check(a.script, a.lib, a.clean)
        return build(a.script, a.lib)
    except ScratchFiles as e:
        print("K3_PAYLOAD: %s" % e)
        return 1


if __name__ == "__main__":
    sys.exit(main())
