# ── Дни числом и словом (ga_days) ──
# Число и слово приходят в текст ОДНИМ аргументом: «на 1 дней» человек видел
# и в меню, и в карточке доступа, а склонять внутри строки словаря нечем.
# days_rule — правило выбора формы для ЭТОГО языка, не текст для человека:
#   last-digit — решает последняя цифра (1, 21, 31 — «день»; 2–4, 22–24 — «дня»;
#                остальные, включая 11–14, — «дней»). Так устроен русский;
#   любое другое значение — единственное число ровно у одного (английский).
I18N[days_rule]="last-digit"
I18N[days_one]="%s день"
I18N[days_few]="%s дня"
I18N[days_many]="%s дней"
# Минуты — по тому же правилу (срок временной ссылки: «действует 5 минут», NC-11)
I18N[minutes_one]="%s минуту"
I18N[minutes_few]="%s минуты"
I18N[minutes_many]="%s минут"
