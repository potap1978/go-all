# ── Битый config.json: отказ вместо скелета ───────────────────────────────────
# Тот же класс, что четыре закрытых дефекта с потерей ключей в users.json.
# Раньше обе записывающие функции начинались с
#     old=$(jq -c . "$CONFIG_FILE") || old=""; [ -n "$old" ] || old=$(_ga_config_skeleton)
# — то есть на НЕРАЗБИРАЕМОМ файле (оборвалась запись, кончилось место, сбой
# ФС) брался пустой скелет, и первая же настройка записывала его поверх: режим,
# домен, порты панели, параметры всех профилей и server_pubkey исчезали молча.
# Отличать «файла ещё нет» от «файл сломан» обязан читатель, а не писатель.

# _ga_json_rescue <файл> → stdout путь спасённой копии (или пусто). Годится для
# любого файла состояния: так спасаются config.json, users.json и stats.json.
# Копия делается ДО отказа и только один раз на каждую версию битого файла:
# имя берёт время правки, поэтому повторные попытки записи не плодят мусор.
# Без копии отказ превращал бы битый файл в могилу — человек чинит config.json
# руками, ошибается ещё раз, и исходного содержимого уже нет.
_ga_json_rescue() {
    local src="${1:-}" epoch stamp dst
    [ -f "$src" ] || return 1
    # Время правки — сначала GNU stat, потом BSD (стенд на macOS). Порядок
    # важен: у GNU `stat -f` означает «файловая система», и с %m он бодро
    # печатает точку монтирования вместо отказа.
    epoch=$(stat -c %Y "$src" 2>/dev/null || stat -f %m "$src" 2>/dev/null) || epoch=""
    [[ "$epoch" =~ ^[0-9]+$ ]] || epoch=$(date -u +%s)
    stamp=$(date -u -d "@$epoch" +%Y%m%dT%H%M%SZ 2>/dev/null || date -u -r "$epoch" +%Y%m%dT%H%M%SZ 2>/dev/null)
    [ -n "$stamp" ] || stamp="$epoch"
    mkdir -p "$BACKUP_DIR" 2>/dev/null || true
    chmod 700 "$BACKUP_DIR" 2>/dev/null || true
    dst="$BACKUP_DIR/$(basename "$src").broken-$stamp"
    if [ ! -f "$dst" ]; then
        cp -p "$src" "$dst" 2>/dev/null || return 1
        chmod 600 "$dst" 2>/dev/null || true
    fi
    printf '%s' "$dst"
}

# _ga_config_intact — 0, если config.json можно читать и переписывать: файла
# нет (законный скелет) или он разбирается. Иначе спасаем копию, объясняем
# человеку, где она и как восстановиться, и ставим код config_corrupt.
# Зовётся ИЗ ТОЙ ЖЕ оболочки, что и запись: в $( ) код ошибки не пережил бы
# подоболочку.
_ga_config_intact() {
    [ -f "$CONFIG_FILE" ] || return 0
    command -v jq >/dev/null 2>&1 || return 0
    # Код возврата jq так же обязателен, как непустой вывод: см. ga_users_intact.
    local parsed prc
    parsed=$(jq -c '.' "$CONFIG_FILE" 2>/dev/null); prc=$?
    [ "$prc" -eq 0 ] && [ -n "$parsed" ] && return 0
    local rescue
    rescue=$(_ga_json_rescue "$CONFIG_FILE") || rescue=""
    ga_set_error config_corrupt
    if [ -n "$rescue" ]; then
        log_error "$(tf err_config_corrupt "$CONFIG_FILE" "$rescue")"
    else
        log_error "$(tf err_config_corrupt_nocopy "$CONFIG_FILE")"
    fi
    log_error "$(tf err_config_corrupt_howto "$BACKUP_DIR")"
    return 1
}

# ga_config_intact — публичное имя той же проверки для модулей. Нужно потому,
# что config.json читает не только этот файл: список установленных профилей
# (lib/amnezia.sh) — такой же вход в конфиг, как ga_config_read, и обязан
# отказывать по тем же правилам. Звать из чужого модуля приватный `_`-помощник
# значило бы договориться об этом молча; парный образец — ga_users_intact.
ga_config_intact() { _ga_config_intact; }

# ga_config_read — весь config.json в stdout. Нет файла → скелет; файл есть, но
# не разбирается → код 1, и вызывающий обязан этот код пробросить наружу
# (парный образец — ga_users_read/ga_users_json).
ga_config_read() {
    _ga_config_intact || return 1
    if [ -f "$CONFIG_FILE" ] && command -v jq >/dev/null 2>&1; then
        jq -c '.' "$CONFIG_FILE" 2>/dev/null
        return 0
    fi
    _ga_config_skeleton
}

# ga_put_json_file <источник> <цель> — положить ГОТОВЫЙ JSON-файл на место
# целиком или не положить вовсе. Нужен восстановлению из бэкапа: прямой `cp`
# сначала обрезает цель, и сбой на середине (кончилось место, отвалился диск)
# оставляет обрезанный config.json или users.json — ровно то состояние, из-за
# которого человек и пришёл восстанавливаться. Здесь работает тот же атомарный
# писатель, что и у всех наших записей: проверка jq, временный файл рядом с
# целью, chmod 600 до переименования, fsync файла и каталога.
ga_put_json_file() {
    local src="${1:-}" dst="${2:-}"
    [ -n "$src" ] && [ -n "$dst" ] && [ -f "$src" ] || return 1
    _ga_write_json "$dst" <"$src"
}

# Путь jq должен быть безопасным: значение приходит из аргументов моста и
# подставляется в программу jq. Разрешаем .a.b, .a["ключ"] и .a[0] — номер
# элемента только цифрами, подставить в программу через него нечего.
#
# Индекса тут не было, и `.client_dns[0]` отвергался наравне с попыткой
# инъекции: экран выбора DNS молча терял строку «Сейчас: 1.1.1.1 и 1.0.0.1» и
# человек выбирал вслепую, не зная, что у него уже стоит. Отказ печатаем в
# журнал: негодный путь — это ошибка в коде, человеку её показывать незачем, а
# потерять её молча — как раз то, что и случилось.
_ga_valid_jq_path() {
    [[ "${1:-}" =~ ^\.[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*|\[\"[A-Za-z0-9_.-]+\"\]|\[[0-9]+\])*$ ]] && return 0
    log_to_file "bad jq path: ${1:-}"
    return 1
}

# ── Снимок config.json на один вызов читающего действия (CPU-03) ─────────────
# Читающие действия моста спрашивают config.json десятки раз, и каждое поле — отдельный jq (status — около трёх
# десятков, при каждом обновлении экрана панели). ga_config_memo_load читает файл ОДИН раз: скалярные поля по
# их пути (.mode, .profiles.awg2.port) — в GA_CFG_MEMO, объекты, массивы и строки с управляющими символами — в
# GA_CFG_NODES (за ними ga_config_get по-прежнему ходит в jq). Включает его диспетчер моста только для readonly-
# действий: такое действие config.json не пишет, а чужие записи идут под замком — снимок даёт ту же картину, что
# дал бы первый jq. Подоболочки наследуют готовый снимок; запись этим процессом его выключает (_ga_write_json).
# Ответ — тот же, что у jq: значение; пусто на null и на отсутствующем поле объекта; путь с индексом, ["ключ"],
# через массив или скаляр — к jq, он ответит или откажет сам.
declare -gA GA_CFG_MEMO=() GA_CFG_NODES=()
GA_CFG_MEMO_ON=0
ga_config_memo_load() {
    local out rec t k v
    GA_CFG_MEMO=(); GA_CFG_NODES=(); GA_CFG_MEMO_ON=0
    [ -f "$CONFIG_FILE" ] && command -v jq >/dev/null 2>&1 || return 0
    # Записи «тип\x1fпуть\x1fзначение\x1e»: управляющих символов в значениях нет (такие поля — тип x, мимо снимка),
    # ключи с чем-то кроме [A-Za-z0-9_.-] — тоже x (такой путь ga_config_get не примет и так).
    out=$(jq -j '
        def seg: if type == "number" then "[\(.)]"
                 elif test("^[A-Za-z_][A-Za-z0-9_]*$") then ".\(.)"
                 elif test("^[A-Za-z0-9_.-]+$") then "[\"\(.)\"]"
                 else "\u0001" end;
        def odd: [explode[] | select(. < 32)] | length > 0;
        (if type == "object" then "o" elif type == "array" then "a" else "x" end) as $rt
        | "\($rt)\u001f.\u001f\u001e",
          (paths as $p
           | ($p | map(seg) | join("")) as $key
           | getpath($p) as $v
           | if ($key | contains("\u0001")) then empty
             elif ($v | type) == "object" then "o\u001f\($key)\u001f\u001e"
             elif ($v | type) == "array" then "a\u001f\($key)\u001f\u001e"
             elif ($v | type) == "string" then
               (if ($v | odd) then "x\u001f\($key)\u001f\u001e" else "s\u001f\($key)\u001f\($v)\u001e" end)
             elif $v == null then "s\u001f\($key)\u001f\u001e"
             else "s\u001f\($key)\u001f\($v | tostring)\u001e" end),
          "E\u001f\u001f\u001e"' "$CONFIG_FILE" 2>/dev/null) || return 0
    # Ровно один документ и конец на месте — иначе (обрыв, второй текст в файле) снимка нет, спрашивает jq.
    [ "${out%E$'\x1f\x1f\x1e'}" != "$out" ] && [ "${out#o$'\x1f'.$'\x1f\x1e'}" != "$out" ] || return 0
    out="${out%E$'\x1f\x1f\x1e'}"
    case "$out" in *"E"$'\x1f\x1f\x1e'*) return 0 ;; esac
    # Записи — массивом одним read (без процессов); поля короткой записи — разбором строки.
    local -a recs=()
    IFS=$'\x1e' read -r -d '' -a recs <<<"$out" || true
    for rec in "${recs[@]}"; do
        case "$rec" in *$'\x1f'*) ;; *) continue ;; esac
        t="${rec%%$'\x1f'*}"; rec="${rec#*$'\x1f'}"
        k="${rec%%$'\x1f'*}"; v="${rec#*$'\x1f'}"
        case "$t" in
            s) GA_CFG_MEMO["$k"]="$v" ;;
            o|a|x) GA_CFG_NODES["$k"]="$t" ;;
        esac
    done
    [ "${GA_CFG_NODES[.]:-}" = o ] || { GA_CFG_MEMO=(); GA_CFG_NODES=(); return 0; }
    GA_CFG_MEMO_ON=1
}

# _ga_config_memo_get <путь> — ответ из снимка (rc 0, значение в stdout) или rc 1: спросить jq.
_ga_config_memo_get() {
    local p="$1" pre
    if [ -n "${GA_CFG_MEMO[$p]+x}" ]; then printf '%s\n' "${GA_CFG_MEMO[$p]}"; return 0; fi
    [ -z "${GA_CFG_NODES[$p]+x}" ] || return 1
    # Поля нет. Пусто (как null у jq) — если путь из одних .имён и ближайший существующий предок — объект;
    # массив, скаляр или странное поле по дороге — к jq.
    [[ "$p" =~ ^(\.[A-Za-z_][A-Za-z0-9_]*)+$ ]] || return 1
    pre="$p"
    while [ "$pre" != "." ]; do
        pre="${pre%.*}"; [ -n "$pre" ] || pre="."
        [ -z "${GA_CFG_MEMO[$pre]+x}" ] || return 1
        if [ -n "${GA_CFG_NODES[$pre]+x}" ]; then
            [ "${GA_CFG_NODES[$pre]}" = o ] || return 1
            printf '\n'
            return 0
        fi
    done
    return 1
}

# ga_config_get <jq-путь> — значение в stdout. null/отсутствие → пустая строка.
ga_config_get() {
    local path="${1:-.}"
    [ -f "$CONFIG_FILE" ] || return 1
    command -v jq >/dev/null 2>&1 || return 1
    if [ "$path" != "." ] && ! _ga_valid_jq_path "$path"; then
        ga_set_error bad_path
        return 1
    fi
    if [ "$GA_CFG_MEMO_ON" = 1 ] && [ "$path" != "." ] && _ga_config_memo_get "$path"; then
        return 0
    fi
    # Не «// empty»: для jq булево false — такая же «пустота», как null, и
    # options.alt_svc=false читался бы как «не задано». Пусто — только null и
    # отсутствие ключа; false печатается словом false.
    local out
    out=$(jq -r "(${path}) | if . == null then empty else . end" "$CONFIG_FILE" 2>/dev/null) || return 1
    printf '%s\n' "$out"
    return 0
}

_ga_config_set_locked() {
    local path="$1" value="$2"
    local old
    # Битый файл — отказ и НИ ОДНОЙ записи. Проверка стоит первой строкой: всё,
    # что ниже, переписывает config.json целиком.
    _ga_config_intact || return 1
    old=$(jq -c '.' "$CONFIG_FILE" 2>/dev/null) || old=""
    # Пусто здесь означает только «файла ещё нет»: сломанный отсеян выше.
    [ -n "$old" ] || old=$(_ga_config_skeleton)
    # Значение пробуем как JSON, и только если оно им не является — как строку.
    # Иначе каждый вызывающий обязан писать ga_config_set .mode '"pro"', и рано
    # или поздно кто-то забудет кавычки, а конфиг молча не изменится.
    # Без -e: с ним jq считает false и null «неуспехом», и website_set_alt_svc off
    # записывал бы строку "false" вместо булева — бот и панель на Python видели бы
    # её как истину. Пустое значение jq молча пропускает (код 0) — это строка.
    # Значение — через окружение, а не аргументом jq: оно бывает секретом (путь панели
    # panel.miniapp_path), а argv любого процесса читает каждый локальный пользователь
    # в /proc/<pid>/cmdline (находка SEC46-02, остаток SR-17).
    local out
    if [ -n "$value" ] && printf '%s' "$value" | jq . >/dev/null 2>&1; then
        out=$(printf '%s' "$old" | GA_CFG_V="$value" jq "${path} = (\$ENV.GA_CFG_V | fromjson)" 2>/dev/null)
    else
        out=$(printf '%s' "$old" | GA_CFG_V="$value" jq "${path} = \$ENV.GA_CFG_V" 2>/dev/null)
    fi
    [ -n "$out" ] || { ga_set_error config_set_failed; return 1; }
    printf '%s' "$out" | _ga_write_json "$CONFIG_FILE"
}

# ga_config_set <jq-путь> <json|строка> — атомарная запись одного поля.
ga_config_set() {
    local path="${1:-}" value="${2:-}"
    # Снимок config.json (ga_config_memo_load) — выключить здесь, в оболочке вызывающего: сама запись идёт в
    # подоболочке конвейера, и выключение внутри _ga_write_json до этой оболочки не дошло бы.
    GA_CFG_MEMO_ON=0
    _ga_valid_jq_path "$path" || { ga_set_error bad_path; log_error "$(tf err_bad_path "$path")"; return 1; }
    ga_with_config_lock _ga_config_set_locked "$path" "$value"
}

_ga_config_merge_locked() {
    local patch="$1"
    local old
    _ga_config_intact || return 1
    old=$(jq -c '.' "$CONFIG_FILE" 2>/dev/null) || old=""
    [ -n "$old" ] || old=$(_ga_config_skeleton)
    local out
    # `*` в jq — рекурсивное слияние объектов: правая часть побеждает по листьям,
    # но не сносит соседние ветки. Именно эта разница спасает profiles.awg3,
    # когда пишут только profiles.awg2.
    out=$(printf '%s' "$old" | jq --argjson new "$patch" '. * $new' 2>/dev/null)
    [ -n "$out" ] || { ga_set_error config_merge_failed; return 1; }
    printf '%s' "$out" | _ga_write_json "$CONFIG_FILE"
}

# ga_config_merge <json> — слить объект поверх текущего конфига.
ga_config_merge() {
    local patch="${1:-}"
    GA_CFG_MEMO_ON=0    # см. ga_config_set
    printf '%s' "$patch" | jq -e 'type == "object"' >/dev/null 2>&1 || {
        ga_set_error invalid_json
        log_error "$(tf err_invalid_json "config.json")"
        return 1
    }
    ga_with_config_lock _ga_config_merge_locked "$patch"
}

# ── Битый users.json: отказ, спасательная копия, ОДНО правило чтения ──────────
# users.json — единственное место, где живут приватные ключи клиентов. «Пусто»
# и «сломано» здесь означают разные вещи, и путать их стоило бы всех ключей:
# неразбираемый файл, принятый за пустой список, первой же записью превращается
# в пустой список НА САМОМ ДЕЛЕ, а в серверный конфиг уезжает ноль пиров.
#
# ga_users_intact — 0, если файл можно читать и переписывать: его ещё нет
# (законный скелет) или он разбирается. Иначе спасаем копию (как у config.json
# и stats.json — договор §3.1), ставим код users_corrupt и объясняем человеку,
# где копия. Зовётся ИЗ ТОЙ ЖЕ оболочки, что и чтение с записью: в $( ) код
# ошибки не пережил бы подоболочку.
ga_users_intact() {
    [ -f "$USERS_FILE" ] || return 0
    # jq нет, а файл есть — прочитать пользователей нечем. Скелет в этом случае
    # означал бы «пользователей нет», и конфиг сервера собрался бы без пиров.
    if ! command -v jq >/dev/null 2>&1; then
        ga_set_error no_jq
        log_error "$(t err_no_jq)"
        return 1
    fi
    # Смотрим И вывод, И код возврата jq. Одного вывода мало: файл, у которого
    # к концу дописался мусор (обрыв записи поверх более длинного старого
    # содержимого — обычное дело), jq печатает разобранную часть и ТОЛЬКО ПОТОМ
    # отказывается, то есть выглядит целым для проверки «вывод непустой».
    # Разбирается — мало: `[]` или `"x"` тоже JSON, но пользователей в нём нет. Раньше
    # status на таком файле отвечал success со словом «файл сломан» вместо числа, а
    # user-list отказывал — одна поломка, два разных ответа (находка SR-55). Форма —
    # объект, .users (если есть) — массив.
    local parsed prc
    parsed=$(jq -c 'if type == "object" and ((.users // []) | type == "array") then . else error("shape") end' \
        "$USERS_FILE" 2>/dev/null); prc=$?
    [ "$prc" -eq 0 ] && [ -n "$parsed" ] && return 0
    local rescue
    rescue=$(_ga_json_rescue "$USERS_FILE") || rescue=""
    ga_set_error users_corrupt
    if [ -n "$rescue" ]; then
        log_error "$(tf err_users_corrupt "$USERS_FILE" "$rescue")"
    else
        log_error "$(tf err_users_corrupt_nocopy "$USERS_FILE")"
    fi
    log_error "$(tf err_users_corrupt_howto "$BACKUP_DIR")"
    return 1
}

# ga_users_read — весь users.json в stdout. Нет файла → пустой скелет,
# чтобы вызывающему не приходилось различать «нет файла» и «нет пользователей».
# Файл есть, но не разбирается → код 1, и вызывающий обязан этот код пробросить
# наружу (парный образец — ga_config_read/_ga_config_intact).
ga_users_read() {
    ga_users_intact || return 1
    if [ -f "$USERS_FILE" ] && command -v jq >/dev/null 2>&1; then
        jq -c '.' "$USERS_FILE" 2>/dev/null
        return 0
    fi
    printf '%s\n' '{"schema":1,"users":[]}'
    return 0
}

# ga_users_load <переменная> — ЕДИНСТВЕННОЕ правильное обращение к users.json
# для всех, кто читает его не ради записи через ga_users_write.
#
# Почему не `x=$(ga_users_read)`: подстановка команды съедает код возврата (её
# код — это код последней команды конвейера, а сам ga_users_read живёт в
# подоболочке, откуда не доходит ни GA_LAST_ERROR_CODE, ни решение отказать).
# Ровно на этом продукт терял ключи: пустая строка от битого файла читалась как
# «пользователей нет».
#
# Проверку делаем В ТЕКУЩЕЙ оболочке (ga_users_intact), и только потом читаем:
# файл к этому моменту уже признан разбираемым, поэтому подстановка безопасна.
# Через временный файл (ga_capture) не идём намеренно — в users.json лежат
# приватные ключи всех клиентов, и класть их на диск ещё раз незачем.
ga_users_load() {
    local __var="${1:?}" __j
    ga_users_intact || return 1
    __j=$(ga_users_read) || { ga_set_error users_corrupt; return 1; }
    [ -n "$__j" ] || __j='{"schema":1,"users":[]}'
    printf -v "$__var" '%s' "$__j"
    return 0
}

_ga_users_write_locked() {
    # Последний рубеж: переписывать users.json поверх НЕРАЗБИРАЕМОГО файла
    # нельзя ни из какой ветки продукта. Проверка стоит первой строкой — всё,
    # что ниже, заменяет файл целиком.
    ga_users_intact || return 1
    _ga_write_json "$USERS_FILE"
}

# ga_users_write — JSON со stdin, атомарно в users.json (0600).
ga_users_write() {
    ga_with_config_lock _ga_users_write_locked
}

# ══════════════════════════════════════════════════════════════════════════════
#  Ответ моста --action (контракт §0.3)
# ══════════════════════════════════════════════════════════════════════════════
# ga_emit_json <status> <message> [k=v …]
# Последняя строка stdout моста. Значение, начинающееся с @json:, вставляется
# как готовый JSON без кавычек — так в ответ попадают массивы и объекты
# (список пользователей, параметры профиля), не превращаясь в строку с \".
ga_emit_json() {
    local status="${1:-error}"
    local message="${2:-}"
    [ $# -ge 2 ] && shift 2 || shift $#

    if command -v jq >/dev/null 2>&1; then
        # Строки — через окружение (local -x живёт до выхода из функции), а не аргументами jq: argv
        # любого процесса читает каждый локальный пользователь в /proc/<pid>/cmdline, а в ответах моста
        # бывают адреса-секреты — путь панели и ссылка на неё в miniapp-on/rotate, в том числе внутри
        # текста сообщения (находка SEC46-02, остаток SR-17). Окружение процесса видит только владелец.
        local -x GA_EJ_STATUS="$status" GA_EJ_MESSAGE="$message"
        local filter='{"status":$ENV.GA_EJ_STATUS,"message":$ENV.GA_EJ_MESSAGE}'
        local kv key val i=0 nj=0 jvals="" fast="$filter"
        # Значения @json: идут в jq через stdin, а не аргументом: один аргумент в Linux не длиннее
        # 128 КБ (MAX_ARG_STRLEN), и уже около сотни пользователей список в ответе моста не
        # помещался — jq не запускался, мост отдавал многострочный мусор вместо JSON, а бот, панель
        # и MCP падали на разборе (находка SR-09, 25.09.2026).
        #
        # Сначала — ОДИН jq на весь ответ (CPU-03): раньше каждое значение @json: проверял свой jq, и ответ status
        # стоил полтора десятка процессов на каждом вызове моста. Каждое значение уходит обёрнутым в [ … ]: склеиться
        # с соседним обёрнутое значение не может, а лишний текст внутри даёт другой счёт или длину. Сошлись счёт и
        # форма — значения ровно те, что пропустила бы проверка по одному; не сошлись (не JSON, два текста в одном) —
        # прежний путь ниже, со строкой на месте негодного значения.
        for kv in "$@"; do
            case "$kv" in *=*) : ;; *) continue ;; esac
            key="${kv%%=*}"
            val="${kv#*=}"
            [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
            i=$((i+1))
            if [ "${val#@str:}" != "$val" ]; then
                local -x "GA_EJ_V${i}=${val#@str:}"
                fast="${fast} + {\"${key}\":\$ENV.GA_EJ_V${i}}"
            elif [ "${val#@json:}" != "$val" ] && [ -n "${val#@json:}" ]; then
                jvals+="[${val#@json:}]"$'\n'
                fast="${fast} + {\"${key}\":\$__j[${nj}][0]}"
                nj=$((nj+1))
            else
                local -x "GA_EJ_V${i}=${val#@json:}"
                fast="${fast} + {\"${key}\":\$ENV.GA_EJ_V${i}}"
            fi
        done
        if [ "$nj" -eq 0 ]; then
            jq -cn "$fast" && return 0
        elif printf '%s' "$jvals" | jq -cn "[inputs] as \$__j
                | if (\$__j | length) == ${nj} and all(\$__j[]; type == \"array\" and length == 1)
                  then ${fast} else error(\"shape\") end" 2>/dev/null; then
            return 0
        fi
        i=0; nj=0; jvals=""
        for kv in "$@"; do
            case "$kv" in *=*) : ;; *) continue ;; esac
            key="${kv%%=*}"
            val="${kv#*=}"
            # Имя поля идёт в программу jq — только безопасный идентификатор
            [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
            i=$((i+1))
            # @str: — свободный текст человека (подпись): всегда строкой, даже если он сам начинается с «@json:»
            # — подпись «@json:true» уходила в ответ user-rename булевым true (находка SR-38).
            if [ "${val#@str:}" != "$val" ]; then
                local -x "GA_EJ_V${i}=${val#@str:}"
                filter="${filter} + {\"${key}\":\$ENV.GA_EJ_V${i}}"
                continue
            fi
            # Валидность JSON — без -e: с ним jq возвращает 1 на значениях false
            # и null, и «reissue_required=@json:false» приезжал бы строкой
            # "false". Пустое значение после @json: — не JSON (jq на пустом
            # вводе молчит и выходит с 0), его отдаём строкой.
            if [ "${val#@json:}" != "$val" ] && [ -n "${val#@json:}" ] \
               && printf '%s' "${val#@json:}" | jq . >/dev/null 2>&1; then
                jvals+="${val#@json:}"$'\n'
                filter="${filter} + {\"${key}\":\$__j[${nj}]}"
                nj=$((nj+1))
            else
                # Не-JSON после @json: отдаём строкой, а не роняем весь ответ:
                # мост обязан вернуть валидный JSON при любом входе.
                local -x "GA_EJ_V${i}=${val#@json:}"
                filter="${filter} + {\"${key}\":\$ENV.GA_EJ_V${i}}"
            fi
        done
        if [ "$nj" -gt 0 ]; then
            printf '%s' "$jvals" | jq -cn "[inputs] as \$__j | ${filter}" && return 0
        else
            jq -cn "$filter" && return 0
        fi
    fi

    # Запасной путь без jq: лучше руками экранированный JSON, чем пустой stdout —
    # бот и MCP разбирают последнюю строку и на пустой падают с transport-ошибкой.
    local out kv key val
    out="{\"status\":\"$(_ga_jesc "$status")\",\"message\":\"$(_ga_jesc "$message")\""
    for kv in "$@"; do
        case "$kv" in *=*) : ;; *) continue ;; esac
        key="${kv%%=*}"; val="${kv#*=}"
        [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
        if [ "${val#@str:}" != "$val" ]; then
            out="${out},\"${key}\":\"$(_ga_jesc "${val#@str:}")\""
        elif [ "${val#@json:}" != "$val" ]; then
            # Одной строкой: договор моста — последняя строка stdout. Переводы строк в JSON
            # бывают только между лексемами, поэтому убрать их безопасно.
            out="${out},\"${key}\":$(printf '%s' "${val#@json:}" | tr -d '\n')"
        else
            out="${out},\"${key}\":\"$(_ga_jesc "$val")\""
        fi
    done
    printf '%s}\n' "$out"
    return 0
}

# ══════════════════════════════════════════════════════════════════════════════
#  Аудит
# ══════════════════════════════════════════════════════════════════════════════
# ga_audit <кто> <действие> <подробности>
# Отдельный файл от общего лога: сюда пишется каждая выдача ключа и каждая
# мутация из бота, панели и MCP. Права 0600 — в подробностях бывают имена
# пользователей и идентификаторы Telegram.
# Экранирование строки для JSON без jq: аудит зовут и там, где jq может не быть
# (ранний этап установки), а битая строка в журнале хуже отсутствующей.
_ga_json_str() {
    local s="${1:-}"
    s="${s//\\/\\\\}"; s="${s//\"/\\\"}"
    s="${s//$'\n'/ }"; s="${s//$'\r'/ }"; s="${s//$'\t'/ }"
    printf '%s' "$s"
}

ga_audit() {
    local who="${1:-unknown}" action="${2:-unknown}" details="${3:-}" iface
    local dir; dir="$(dirname "$AUDIT_LOG")"
    [ -d "$dir" ] || mkdir -p "$dir" 2>/dev/null || return 0
    if [ ! -e "$AUDIT_LOG" ]; then
        touch "$AUDIT_LOG" 2>/dev/null || return 0
        chmod 600 "$AUDIT_LOG" 2>/dev/null || true
    fi
    # Через какой интерфейс пришли: «panel:tester» → panel, «bot:123» → bot,
    # «agent:a-1f2e» → mcp, «ssh» → ssh. Отдельным полем, чтобы журнал можно
    # было читать по интерфейсам, а не угадывать по виду строки.
    # Голое «panel»/«bot» — тоже интерфейс: так их передают проверки и старые
    # вызовы, и без этих вариантов действие панели записывалось как «ssh».
    case "$who" in
        panel|panel:*)     iface=panel ;;
        bot|bot:*)         iface=bot ;;
        agent:*|mcp|mcp:*) iface=mcp ;;
        *)                 iface=ssh ;;
    esac
    # Одна строка — один объект JSON, один формат на весь продукт (CONTRACT §7.1).
    # Раньше ядро писало TSV, панель JSON, а MCP свободный текст — три формата в
    # одном файле, и собрать «кто что сделал» было нечем (DEFECTS §2.2).
    # stage=effect: это запись о СЛУЧИВШЕМСЯ на сервере; интерфейсы пишут свои
    # записи stage=call — кто и о чём попросил.
    { printf '{"ts":"%s","iface":"%s","stage":"effect","who":"%s","action":"%s","details":"%s"}\n' \
        "$(ga_now)" "$iface" "$(_ga_json_str "$who")" "$(_ga_json_str "$action")" \
        "$(_ga_json_str "$details")" >> "$AUDIT_LOG"; } 2>/dev/null || true
    return 0
}

# ══════════════════════════════════════════════════════════════════════════════
#  Очередь событий для бота (файл-очередь, docs/BOT.md §6)
# ══════════════════════════════════════════════════════════════════════════════
# ga_notify <событие> [json-объект с полями]
# Один файл = одно событие = одна строка JSON {ts, event, …}. Файл появляется
# в каталоге атомарно (mktemp + mv): бот читает по обходу раз в 30 с и удаляет,
# а полузаписанный файл он никогда не увидит. Каталог — /run/goamnezia/notify
# (GOAMNEZIA_NOTIFY_DIR на стенде). Пишут сюда таймер лимитов (users.sh),
# сторож контейнеров и проверка обновлений; читает только бот. Каталог 0700,
# файлы 0600 — в событиях имена пользователей.
#
# Предел очереди. Читателя может не быть вовсе: бота не поставили, он упал или
# токен отозвали — а таймеры продолжают писать. За одну ночь рассогласования
# версий Docker очередь набрала десятки файлов и никто их не забрал; на tmpfs
# /run это ещё и память. Держим не больше GOAMNEZIA_NOTIFY_MAX файлов: лишние
# (самые старые — имя начинается с метки времени, поэтому лексический порядок
# и есть хронологический) выбрасываем. Свежие события важнее старых: человек
# читает уведомление, чтобы узнать, что сейчас, а не что было ночью.
GA_NOTIFY_MAX_DEFAULT=200

# ga_notify_trim <каталог> [предел] — обрезать очередь до предела (0 — не
# ограничивать). Тихая: очередь уведомлений не повод валить таймер.
ga_notify_trim() {
    local dir="$1" max="${2:-${GOAMNEZIA_NOTIFY_MAX:-$GA_NOTIFY_MAX_DEFAULT}}" n extra f
    [ -d "$dir" ] || return 0
    [[ "$max" =~ ^[0-9]+$ ]] || return 0
    [ "$max" -gt 0 ] || return 0
    n=$(find "$dir" -maxdepth 1 -name '*.json' -type f 2>/dev/null | wc -l | tr -d ' ')
    [[ "$n" =~ ^[0-9]+$ ]] || return 0
    [ "$n" -gt "$max" ] || return 0
    extra=$((n - max))
    while IFS= read -r f; do
        [ -n "$f" ] || continue
        rm -f "$f" 2>/dev/null
    done < <(find "$dir" -maxdepth 1 -name '*.json' -type f 2>/dev/null | sort | head -n "$extra")
    return 0
}

ga_notify() {
    local event="${1:-}" extra="${2:-{\}}" dir ts tmp line
    [ -n "$event" ] || return 1
    command -v jq >/dev/null 2>&1 || return 1
    dir="${GOAMNEZIA_NOTIFY_DIR:-${LOCK_DIR:-/run/goamnezia}/notify}"
    mkdir -p "$dir" 2>/dev/null || return 1
    chmod 700 "$dir" 2>/dev/null
    ts=$(ga_now)
    printf '%s' "$extra" | jq -e 'type == "object"' >/dev/null 2>&1 || extra='{}'
    line=$(jq -cn --arg ts "$ts" --arg ev "$event" --argjson extra "$extra" \
        '{ts: $ts, event: $ev} + $extra') || return 1
    tmp=$(mktemp "$dir/.tmp.XXXXXX") || return 1
    printf '%s\n' "$line" >"$tmp"
    chmod 600 "$tmp"
    # Порядковый номер в имени: два события за одну секунду из одного процесса
    # не должны затирать друг друга. Номер дополняем нулями до четырёх знаков,
    # иначе внутри одной секунды лексический порядок имён расходится с
    # хронологическим (_10 встаёт раньше _2), а по нему идут и обрезка очереди,
    # и чтение ботом.
    GA_NOTIFY_SEQ=$((${GA_NOTIFY_SEQ:-0} + 1))
    mv "$tmp" "$(printf '%s/%s_%s_%04d.json' "$dir" "${ts//[:-]/}" "$$" "$GA_NOTIFY_SEQ")" || return 1
    ga_notify_trim "$dir"
    return 0
}

# ══════════════════════════════════════════════════════════════════════════════
#  Дисклеймер (порт из goTelegram). Инфо-режим или gate (--gate + маркер).
# ══════════════════════════════════════════════════════════════════════════════
show_disclaimer() {
    local gate=false
    [ "${1:-}" = "--gate" ] && gate=true

    if $gate && [ -f "${GOAMNEZIA_DIR}/.disclaimer-accepted" ]; then
        return 0
    fi

    echo ""
    echo -e "  ${BOLD}${WHITE}$(t disclaimer_title)${NC}"
    echo -e "  ${DIM}$(printf '─%.0s' {1..58})${NC}"
    echo -e "  ${YELLOW}$(t disclaimer_intro)${NC}"
    echo ""
    echo -e "  ${BOLD}$(t disclaimer_uses_header)${NC}"
    echo -e "  ${DIM}$(t disclaimer_uses_1)${NC}"
    echo -e "  ${DIM}$(t disclaimer_uses_2)${NC}"
    echo -e "  ${DIM}$(t disclaimer_uses_3)${NC}"
    echo -e "  ${DIM}$(t disclaimer_uses_4)${NC}"
    echo ""
    echo -e "  ${BOLD}$(t disclaimer_legal_header)${NC}"
    echo -e "  ${DIM}$(t disclaimer_legal_1)${NC}"
    echo -e "  ${DIM}$(t disclaimer_legal_2)${NC}"
    echo -e "  ${DIM}$(t disclaimer_legal_3)${NC}"
    echo -e "  ${YELLOW}$(t disclaimer_legal_4)${NC}"
    echo ""
    echo -e "  ${BOLD}${RED}$(t disclaimer_prohibited_header)${NC}"
    echo -e "  ${DIM}$(t disclaimer_prohibited_1)${NC}"
    echo -e "  ${DIM}$(t disclaimer_prohibited_2)${NC}"
    echo -e "  ${DIM}$(t disclaimer_prohibited_3)${NC}"
    echo ""
    echo -e "  ${YELLOW}$(t disclaimer_anonymity_note)${NC}"
    echo ""

    if ! $gate; then
        return 0   # инфо-режим для пункта меню «О программе»
    fi

    # Gate: ответ читаем из управляющего терминала, если stdin не tty
    local _src=/dev/stdin
    if [ ! -t 0 ] && [ -r /dev/tty ]; then _src=/dev/tty; fi
    echo -e "  ${BOLD}$(t disclaimer_accept_prompt)${NC}"
    echo -e "  ${CYAN}1)${NC} $(t disclaimer_agree)"
    echo -e "  ${CYAN}2)${NC} $(t disclaimer_decline)"
    local ans
    while true; do
        echo -ne "  ${BOLD}$(t disclaimer_choice)${NC} "
        read -r ans < "$_src" || ans=""
        ans="$(printf '%s' "$ans" | tr -d '[:space:]')"
        case "$ans" in
            1|[Yy]|[Дд])
                mkdir -p "$GOAMNEZIA_DIR" 2>/dev/null
                { ga_now > "${GOAMNEZIA_DIR}/.disclaimer-accepted"; } 2>/dev/null || true
                echo -e "  ${DIM}$(tf disclaimer_accepted_marker_hint "${GOAMNEZIA_DIR}/.disclaimer-accepted")${NC}"
                echo ""
                return 0 ;;
            2|[Nn]|[Нн]|"")
                log_warning "$(t disclaimer_declined)"
                return 1 ;;
            *)
                log_warning "$(t invalid_choice)" ;;
        esac
    done
}
