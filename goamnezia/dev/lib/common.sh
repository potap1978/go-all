}

# validate_domain — домен целиком, а не построчно.
# Проверять через `echo "$d" | grep -qE '^…$'` нельзя: grep сопоставляет по
# строкам и говорит «подходит», если подошла хотя бы одна. Многострочное
# значение вида «a.com\n server_name evil;» проходило целиком, а дальше домен
# подставляется в конфиг nginx и в Endpoint клиентского .conf. [[ =~ ]]
# сопоставляет строку целиком, поэтому перевод строки отвергается.
# Зона верхнего уровня — буквы или punycode (xn--p1ai — это .рф): домен с кириллицей Ленивый Pro переводит в
# punycode (lib/modes.sh), и сертификат, nginx и ключи получают его в таком виде.
validate_domain() {
    [[ "${1:-}" =~ ^([a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?\.)+([a-zA-Z]{2,}|[xX][nN]--[a-zA-Z0-9]([a-zA-Z0-9-]{0,57}[a-zA-Z0-9])?)$ ]]
}

# ── Генерация случайного hex ──────────────────────────────────────────────────
generate_hex() {
    local len="${1:-32}"
    openssl rand -hex "$((len/2))" 2>/dev/null || head -c "$((len/2))" /dev/urandom | od -An -tx1 | tr -d ' \n'
}

# ── Конец ввода ───────────────────────────────────────────────────────────────
# GA_INPUT_EOF=1 — вопрос остался без ответа: ввод кончился (терминал закрылся, сессия оборвалась, запуск из
# конвейера). Ставят все общие вопросы ниже (confirm, confirm_phrase, ga_ask, ga_ask_optional, ga_read_paste,
# select_option) и вопросы мастера; снимает тот, кто начинает сценарий (мастер первой установки — в начале).
# Возвращаемые коды при этом прежние: по ним одним «нет» человека не отличить от «никого нет», а мастеру это
# различие главное — раньше конец ввода он принимал за Enter и сам ставил профили по умолчанию (находка INST-02,
# сервер 168).
# Отметку видно только в той же оболочке: зовущий через $( … ) её теряет, мастер зовёт вопросы через ga_capture.
GA_INPUT_EOF=0

# ── Подтверждение ─────────────────────────────────────────────────────────────
confirm() {
    local msg="${1:-$(t confirm_default)}"
    local ans=""
    # Подсказка цифрами: в меню продукта управление только цифрами, и «[y/N]»
    # посреди цифровых пунктов заставляло человека переключать раскладку ради
    # одной буквы. Прежние ответы (y, да, д) по-прежнему принимаются — у тех,
    # кто привык, ничего не сломается.
    # «[1 — да, 0 — нет]» — одним куском, как «[0 — назад]» (LC-17): длинный вопрос Ленивого Pro рвал подсказку
    # посередине — «0⏎ — нет]» (LZ-06). Пробелы внутри — неразрывные (C2 A0), перенос встаёт только перед скобкой.
    local hint
    hint=$(t confirm_hint)
    echo -ne "  $(ga_win_wrap "${msg} ${hint// /$'\xc2\xa0'}:" 2) " >&2
    # Читаем из управляющего терминала, а не из stdin: при запуске через
    # bootstrap (curl|bash) stdin — это тело скрипта, а не человек. Обычный read
    # получал EOF, пустой ответ трактовался как согласие, и необратимое
    # выполнялось БЕЗ спроса. Нет tty и нет ввода → «нет».
    # `[ -r /dev/tty ]` говорит лишь о правах на файл: без управляющего
    # терминала (запуск из конвейера, из cron, из юнита) открытие всё равно не
    # удаётся, и оболочка печатала человеку сырое «/dev/tty: Device not
    # configured» — подавление у read неудачу ПЕРЕНАПРАВЛЕНИЯ не гасит, нужны
    # скобки вокруг всей конструкции. Не вышло с терминала: читаем stdin, только
    # если он сам терминал; из конвейера ответа не берём вовсе — там «человеком»
    # оказалось бы тело скрипта (curl | bash), и необратимое пошло бы без спроса.
    # Ответа нет вовсе (конец ввода, терминала нет) — «нет» и отметка GA_INPUT_EOF: мастер по ней
    # останавливается, а не идёт дальше без человека (INST-02).
    if ! { IFS= read -r ans </dev/tty; } 2>/dev/null; then
        if [ -t 0 ]; then
            IFS= read -r ans || { ans="n"; GA_INPUT_EOF=1; }
        else
            ans="n"; GA_INPUT_EOF=1
        fi
    fi
    ans="$(printf '%s' "$ans" | tr -d '[:space:]' | tr 'A-Z' 'a-z')"
    # Литералы, а не класс [Дд]: класс с кириллицей сопоставляется побайтово и
    # вне UTF-8 локали пропускал «н» как согласие на удаление.
    case "$ans" in
        1|y|yes|д|да) return 0 ;;
        *) return 1 ;;
    esac
}

# ── Подтверждение набором фразы ───────────────────────────────────────────────
# Разрушительное в SSH было защищено слабее, чем в боте и в панели: там надо
# набрать фразу, здесь хватало одной «y» — а SSH и есть тот интерфейс, где
# человек сидит под root. confirm_phrase просит набрать ровно ту строку, которую
# показал, и сравнивает без учёта регистра и краевых пробелов (человек и так уже
# доказал намерение, придираться к Shift незачем).
#
#   confirm_phrase <фраза> <вопрос> [<строка приглашения>] [<ключ строки отказа>]
#
# Строка приглашения — готовый текст вместо «Наберите «…» для подтверждения»: когда фраза сама по себе ничего не
# говорит (порт профиля, D-5), в ней сказано, что это и откуда. Ключ строки отказа — словарный ключ вместо
# «Отменено.» и «Набрано не то…», когда отменяется не всё (RB4-1: при Lite → Pro сайт уже поднят, отменён только
# перенос порта VPN).
#
# rc 0 — набрано верно; 1 — набрано что-то другое, пусто или нет терминала.
# Ввод, как и у confirm, берём с управляющего терминала: через `curl | bash`
# stdin занят телом скрипта, и обычный read получил бы EOF.
confirm_phrase() {
    local phrase="${1:-}" msg="${2:-}" ask="${3:-}" cancel_key="${4:-}" ans=""
    [ -n "$phrase" ] || return 1
    [ -n "$msg" ] && echo -e "  ${msg}" >&2
    [ -n "$ask" ] || ask=$(tf confirm_phrase_ask "$phrase")
    echo -ne "  ${WHITE}${ask}${NC} " >&2
    # Как у confirm: `[ -r /dev/tty ]` говорит лишь о правах на файл — без управляющего терминала открытие не
    # удаётся, и человек видел сырое «/dev/tty: No such device» (находка SR-53). Скобки гасят и неудачу
    # перенаправления. Не вышло с терминала — stdin, только если он сам терминал; из конвейера — «нет».
    if ! { IFS= read -r ans </dev/tty; } 2>/dev/null; then
        if [ -t 0 ]; then
            IFS= read -r ans || { ans=""; GA_INPUT_EOF=1; }
        else
            ans=""; GA_INPUT_EOF=1
        fi
    fi
    ans="${ans#"${ans%%[![:space:]]*}"}"
    ans="${ans%"${ans##*[![:space:]]}"}"
    if [ "${ans,,}" = "${phrase,,}" ]; then
        return 0
    fi
    # Одна строка об отказе (LH-3): пусто — «Отменено.», набрано другое — «Набрано не то — отменено…». Вызывающий
    # своё «Отменено.» после отказа не печатает.
    if [ -n "$cancel_key" ]; then log_info "$(t "$cancel_key")"
    elif [ -z "$ans" ]; then log_info "$(t cancelled)"; else log_info "$(t confirm_phrase_mismatch)"; fi
    return 1
}

# ── Вопрос с переспросом ──────────────────────────────────────────────────────
# Ошибка ввода раньше выбрасывала из сценария целиком: человек опечатался в
# порту — и снова ищи нужный пункт меню. Здесь один цикл на все такие вопросы:
#
#   ga_ask <подсказка> <regex-проверка> <сообщение об ошибке> [умолчание] [попыток]
#
# stdout — принятое значение (функцию зовут через $( )), весь UI — в stderr.
#   • пустой ввод при заданном умолчании — берём умолчание;
#   • пустой ввод без умолчания — сообщение об ошибке и переспрос;
#   • «0» — явная отмена: rc 1, ничего не печатаем;
#   • не прошло проверку — сообщение и переспрос, всего <попыток> раз (по
#     умолчанию 3); после последней попытки rc 2 — вызывающий решает, брать ли
#     предложенное значение, и обязан сказать об этом вслух;
#   • EOF (нет терминала) — умолчание, если оно есть, иначе rc 1: молчаливого
#     зацикливания на 100 % CPU быть не должно. Отметка GA_INPUT_EOF — тоже
#     (выше): мастер по ней останавливается, а не берёт умолчание (INST-02).
ga_ask() {
    local prompt="${1:-}" re="${2:-.}" errmsg="${3:-}" def="${4:-}" tries="${5:-3}" v i hint=""
    [[ "$tries" =~ ^[0-9]+$ ]] && [ "$tries" -gt 0 ] || tries=3
    # «0 — назад» — договор всего меню, и говорить о нём обязан тот, кто
    # спрашивает. Иначе про выход знают только на тех экранах, где кто-то
    # вспомнил дописать подсказку руками, а на «Подсеть профиля» и «MTU» человек
    # искал выход и не находил (DEFECTS §3.10). Там, где спрашивают номер пункта
    # (^[0-9]+$), подсказки нет: у списка своя строка «0) Назад», и 0 там —
    # законный ответ, а не отмена.
    # Признак «спрашивают номер пункта» — не регулярка, а сам вопрос: у списка
    # уже напечатана своя строка «0) Назад», и подсказка в приглашении её
    # задваивала (DEFECTS §4.3). Слово «Выбор» принадлежит только таким экранам.
    if [ "$re" != '^[0-9]+$' ] && [ "$prompt" != "$(t choose)" ]; then
        # «[0 — назад]» — одним куском: перенос посреди подсказки давал «[0 —⏎ назад]» (находка LC-17). Пробелы
        # внутри — неразрывные (байты UTF-8 C2 A0 — от локали не зависят), перенос встаёт только перед скобкой.
        local zb
        zb=$(t ask_zero_back)
        hint=" ${DIM}${zb// /$'\xc2\xa0'}${NC}"
    fi
    for ((i = 0; i < tries; i++)); do
        echo -ne "  $(ga_win_wrap "${WHITE}${prompt}${NC}${hint}${WHITE}:${NC}" 2) " >&2
        if ! IFS= read -r v; then
            echo "" >&2
            GA_INPUT_EOF=1
            [ -n "$def" ] && { printf '%s' "$def"; return 0; }
            return 1
        fi
        v="${v#"${v%%[![:space:]]*}"}"
        v="${v%"${v##*[![:space:]]}"}"
        if [ -z "$v" ]; then
            [ -n "$def" ] && { printf '%s' "$def"; return 0; }
        elif [ "$v" = "0" ] && [ "$re" != '^[0-9]+$' ]; then
            return 1
        elif [[ "$v" =~ $re ]]; then
            printf '%s' "$v"
            return 0
        fi
        [ -n "$errmsg" ] && log_error "$errmsg"
    done
    return 2
}

# ga_ask_optional <подсказка> <regex> <сообщение> — то же, но пустой ввод это
# ОСМЫСЛЕННЫЙ ответ («без лимита», «бессрочно»), а мусор — переспрос. Печатает
# пустую строку и возвращает 0, когда человек нажал Enter; rc 1 — отмена или
# три промаха подряд.
ga_ask_optional() {
    local prompt="${1:-}" re="${2:-.}" errmsg="${3:-}" tries="${4:-3}" v i
    [[ "$tries" =~ ^[0-9]+$ ]] && [ "$tries" -gt 0 ] || tries=3
    for ((i = 0; i < tries; i++)); do
        echo -ne "  $(ga_win_wrap "${WHITE}${prompt}:${NC}" 2) " >&2
        # Конец ввода (Ctrl-D, оборванная сессия). Ответ — пустой, как Enter, и отметка GA_INPUT_EOF: мастер
        # по ней останавливается, а не идёт дальше «с умолчаниями» без человека (INST-02). На экранах, где
        # пустой ответ ОСЛАБЛЯЕТ ограничение (лимит, срок, новый пользователь, почта), вызывающий ставит
        # GA_EOF_CANCEL=1: Ctrl-D — отмена, а не «без лимита» с зелёной галочкой (находка SR-52, 25.09.2026).
        if ! IFS= read -r v; then
            echo "" >&2
            GA_INPUT_EOF=1
            [ "${GA_EOF_CANCEL:-0}" = 1 ] && return 1
            printf ''; return 0
        fi
        v="${v#"${v%%[![:space:]]*}"}"
        v="${v%"${v##*[![:space:]]}"}"
        if [ -z "$v" ]; then printf ''; return 0; fi
        if [[ "$v" =~ $re ]]; then printf '%s' "$v"; return 0; fi
        [ -n "$errmsg" ] && log_error "$errmsg"
    done
    return 1
}

# ── Длинная вставка: ссылка vpn:// и текст .conf ──────────────────────────────
# Терминал в обычном (каноническом) режиме собирает строку сам и режет её: в Linux — на 4095 байтах, в macOS —
# на 1024. Длинная ссылка vpn:// (AmneziaWG 2.0 и 3.1 с I1–I5) доходила до привязки ключа обрезанной, и та
# отвечала config_unreadable (находки TK-3, TAIL-1). Здесь строку собирает сам bash: `read -n` читает по знаку
# в неканоническом режиме, и предела у строки нет.
#
# Одного `read -n` мало: после каждой строки (и после первого знака — см. Ctrl-D ниже) read сам возвращает
# терминал в канонический режим с эхом, и кусок вставки, пришедший в этот промежуток, ядро обработало бы
# по-старому — обрезало и показало эхом (вставка идёт по сети кусками). Поэтому на всю вставку терминал держится
# неканоническим (при -s — и без эха) одной командой stty, а в прежний вид возвращается в конце и ловушкой на
# INT, TERM и HUP: Ctrl-C восстанавливает терминал и прерывает меню, как прежде, — прежние ловушки возвращаются
# на место, и сигнал отдаётся заново. Свои ловушки на время вставки — цена: один read после Ctrl-C вернул бы
# терминал и сам, но промежутков между строками он не закрывает.
# Правку строки в неканоническом режиме ядро не делает — её делает помощник: Backspace стирает знак, Ctrl-U —
# строку; Ctrl-D в начале строки — конец ввода сразу, как раньше (первый знак строки читается отдельно).
#
#   ga_read_paste <переменная> [-s] [-l <строк>] [-w <секунд>]
#
#   -s  без эха (ключи);
#   -l  самое большее строк (по умолчанию 300);
#   -w  пауза, после которой вставка кончилась (по умолчанию 1 с). Строки, идущие следом за первой
#       (многострочный .conf), дочитываются, пока идут; пустые строки в начале вставки пропускаются, если за
#       ними что-то пришло (текст из чата с переводом строки впереди — находка TK-2).
#
# rc 0 — текст: строки через перевод строки, без \r; пустой — человек нажал Enter, ничего не вставив.
# rc 1 — конец ввода раньше всякого текста (терминал закрылся, Ctrl-D): отметка GA_INPUT_EOF, как у вопросов выше.
ga_read_paste() {
    local __var="$1" __s="" __max=300 __wait=1 __tty="" __text="" __line="" __n=0 __rc=0 __intr=0
    local __o_int="" __o_term="" __o_hup=""
    shift
    while [ $# -gt 0 ]; do
        case "$1" in
            -s) __s=-s ;;
            -l) __max="${2:-300}"; shift ;;
            -w) __wait="${2:-1}"; shift ;;
        esac
        shift
    done
    [[ "$__max" =~ ^[1-9][0-9]*$ ]] || __max=300
    # Не терминал (конвейер, файл) — предела строки нет и держать нечего.
    if [ -t 0 ]; then
        __tty=$(stty -g 2>/dev/null) || __tty=""
    fi
    if [ -n "$__tty" ]; then
        __o_int=$(trap -p INT); __o_term=$(trap -p TERM); __o_hup=$(trap -p HUP)
        trap '_ga_paste_signal INT' INT
        trap '_ga_paste_signal TERM' TERM
        trap '_ga_paste_signal HUP' HUP
        if [ -n "$__s" ]; then
            stty -icanon -echo min 1 time 0 2>/dev/null
        else
            stty -icanon min 1 time 0 2>/dev/null
        fi
    fi
    # Первая строка ждёт человека сколько угодно. Пустая — «назад», если следом за паузу ничего не пришло.
    _ga_paste_line __line "$__s" "" || __rc=$?
    if [ "$__rc" -eq 0 ]; then
        while [ -z "${__line//[[:space:]]/}" ] && [ "$__intr" = 0 ]; do
            _ga_paste_line __line "$__s" "$__wait" || { __line=""; break; }
        done
        __text="$__line"
        __n=1
        while [ -n "$__text" ] && [ "$__n" -lt "$__max" ] && [ "$__intr" = 0 ]; do
            _ga_paste_line __line "$__s" "$__wait" || break
            __text+=$'\n'"$__line"
            __n=$((__n + 1))
        done
    fi
    _ga_paste_done
    if [ "$__rc" -ne 0 ] || [ "$__intr" != 0 ]; then
        printf -v "$__var" '%s' ""
        GA_INPUT_EOF=1
        return 1
    fi
    printf -v "$__var" '%s' "$__text"
    return 0
}

# Одна строка вставки: первый знак — отдельно (Ctrl-D в начале строки — конец ввода сразу, без Enter), остаток —
# до перевода строки. С паузой (-w, строки следом за первой) тишина посреди строки — не её конец: вставка идёт по
# сети кусками, и строка дочитывается; тишина до первого знака — конец вставки.
# rc 0 — строка; 1 — конец ввода; 2 — тишина.
_ga_paste_line() {
    local __v="$1" __t="$3" __c="" __part="" __buf="" __rc=0
    local -a __o=(-r)
    [ -n "$2" ] && __o+=(-s)
    [ -n "$__t" ] && __o+=(-t "$__t")
    while :; do
        __c=""; __rc=0
        IFS= read "${__o[@]}" -n 1 __c || __rc=$?
        [ "$__rc" -gt 128 ] && return 2
        [ "$__rc" -ne 0 ] && [ -z "$__c" ] && return 1
        case "$__c" in
            $'\x04') return 1 ;;
            $'\x7f'|$'\b'|$'\x15') continue ;;
            "") printf -v "$__v" '%s' ""; return 0 ;;
        esac
        break
    done
    __buf="$__c"
    while :; do
        __part=""; __rc=0
        IFS= read "${__o[@]}" -n 65536 __part || __rc=$?
        __buf+="$__part"
        if [ "$__rc" -gt 128 ]; then
            # Пауза: строка ещё идёт — читаем дальше; ничего не пришло — хвост без перевода строки и есть её конец.
            [ -n "$__part" ] && continue
            break
        fi
        [ "$__rc" -ne 0 ] && break
        # Ровно 65536 знаков — предел одного read, а не конец строки.
        [ "${#__part}" -ge 65536 ] && continue
        break
    done
    __buf="${__buf%$'\r'}"
    _ga_paste_edit __buf
    printf -v "$__v" '%s' "$__buf"
    return 0
}

# Правка, которую в неканоническом режиме не сделало ядро: Ctrl-U — строка заново, Backspace (DEL или ^H) стирает
# знак перед собой; Ctrl-D посреди строки ничего не значит — в каноническом режиме он лишь отдаёт набранное раньше
# Enter. В ссылке vpn:// и тексте .conf этих знаков не бывает: без них строка не трогается.
_ga_paste_edit() {
    local __e="${!1}"
    case "$__e" in
        *[$'\x04\x08\x15\x7f']*) ;;
        *) return 0 ;;
    esac
    __e="${__e//$'\x04'/}"
    __e="${__e##*$'\x15'}"
    while [[ "$__e" == *[$'\x08\x7f']* ]]; do
        if [[ "$__e" == [$'\x08\x7f']* ]]; then
            __e="${__e:1}"
        else
            __e="${__e/?[$'\x08\x7f']/}"
        fi
    done
    printf -v "$1" '%s' "$__e"
}

# Терминал и ловушки — в прежний вид (конец вставки или сигнал посреди неё).
_ga_paste_done() {
    [ -n "$__tty" ] || return 0
    stty "$__tty" 2>/dev/null
    eval "${__o_int:-trap - INT}"
    eval "${__o_term:-trap - TERM}"
    eval "${__o_hup:-trap - HUP}"
    __tty=""
}

# Сигнал посреди вставки: терминал и ловушки — прежние, и сигнал заново — с тем действием, что было до вставки
# (без ловушки Ctrl-C прерывает меню, как прежде).
_ga_paste_signal() {
    _ga_paste_done
    __intr=1
    kill -s "$1" "$BASHPID" 2>/dev/null
}

# ── Выбор из списка ───────────────────────────────────────────────────────────
# Весь UI — в stderr, на stdout только номер: функцию зовут через $( ).
select_option() {
    local title="$1"
    shift
    local options=("$@")

    echo "" >&2
    echo -e "  ${BOLD}${WHITE}${title}${NC}" >&2
    # Линейка на всю ширину меню и перенос длинных вариантов: ответы про уровни доступа шли одной
    # строкой за край окна, а линейка в 50 знаков не совпадала с остальными экранами.
    echo -e "  ${DIM}$(printf '─%.0s' $(seq 1 "${GA_UI_W:-76}"))${NC}" >&2
    local i=1 opt
    for opt in "${options[@]}"; do
        echo -e "  ${CYAN}${i})${NC} $(ga_wrap "$opt" $(( ${GA_UI_W:-76} - 5 )) 5 | sed '1s/^     //')" >&2
        i=$((i+1))
    done
    # Выход с экрана обязан быть на каждом уровне: без «0 — назад» человек,
    # открывший вопрос по ошибке, получал от вызывающего красное «Неверный
    # выбор» и вылетал из всего сценария — а он всего лишь передумал.
    echo -e "  ${CYAN}0${NC}) $(t back)" >&2
    echo -e "  ${DIM}$(printf '─%.0s' $(seq 1 "${GA_UI_W:-76}"))${NC}" >&2
    echo -ne "  ${WHITE}$(t choose):${NC} " >&2
    local choice
    read -r choice || { choice=0; GA_INPUT_EOF=1; }
    echo "$choice"
}

