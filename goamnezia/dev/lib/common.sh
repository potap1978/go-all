PROFILE_IDS="awg3 awg2 awg1"

# ── Порты профилей (контракт §2) ──────────────────────────────────────────────
# Основной диапазон — 1024–9999 (решение владельца 10.09.2026): в корпоративных
# и мобильных сетях исходящий UDP выше 10000 режут заметно чаще, чем «низкий»
# порт, и ключ, который не поднимается из гостиничного Wi-Fi, бесполезен.
# Прежний диапазон 30000–49999 (так порты выбирает само приложение Amnezia)
# остался запасным: если в низком всё занято, берём его и говорим об этом.
GA_PORT_LOW_MIN=1024
GA_PORT_LOW_MAX=9999
GA_PORT_HIGH_MIN=30000
GA_PORT_HIGH_MAX=49999

# Общеизвестные порты, которые в низком диапазоне не занимаем: даже если сейчас
# свободны, завтра сюда встанет панель хостера, база или чужой прокси — и VPN
# молча отвалится. Список короткий и намеренно «на глаз»: полный /etc/services
# выбросил бы половину диапазона.
GA_PORT_WELLKNOWN="1080 1194 1234 1433 1521 1701 1723 1812 1813 1900 1935 1985 1986
2049 2082 2083 2086 2087 2095 2096 2181 2375 2376 3000 3128 3306 3389 3478 4444
4500 5000 5060 5061 5222 5353 5432 5601 5900 6379 6443 8000 8006 8080 8081 8088
8443 8888 9000 9090 9100 9200 9300 9999"

# ga_port_wellknown <порт> → 0, если порт из списка выше.
ga_port_wellknown() {
    local p="${1:-}" w
    for w in $GA_PORT_WELLKNOWN; do
        [ "$p" = "$w" ] && return 0
    done
    return 1
}

# Равномерное случайное число в диапазоне. $RANDOM даёт 0..32767, поэтому для
# диапазонов шире этого склеиваем два броска — иначе верхняя часть выпадала бы
# вдвое реже (грабли прежнего _random_port).
ga_port_random() {
    local lo="${1:-1024}" hi="${2:-9999}" span
    span=$(( hi - lo + 1 ))
    if command -v shuf >/dev/null 2>&1; then
        local p
        p=$(shuf -i "${lo}-${hi}" -n 1 2>/dev/null) || p=""
        [ -n "$p" ] && { printf '%s' "$p"; return 0; }
    fi
    printf '%s' "$(( lo + ((RANDOM << 15 | RANDOM) % span) ))"
}

# ── Код последней ошибки ──────────────────────────────────────────────────────
# Библиотеки не делают exit, а мосту --action нужен машиночитаемый код отказа.
# Функция, которая знает причину, кладёт её сюда; вызывающий отдаёт наружу
# через ga_emit_json error … code=…
# ВАЖНО про область видимости: функция, вызванная через $( ), работает в
# ПОДОБОЛОЧКЕ, и записанный там код наружу не попадает. Кто хочет прочитать
# GA_LAST_ERROR_CODE, зовёт функцию без подстановки — `get_arch >/dev/null`,
# а результат при нужде забирает файлом или отдельным вызовом.
GA_LAST_ERROR_CODE=""
ga_set_error() { GA_LAST_ERROR_CODE="${1:-}"; return 0; }

# ── Цвета ─────────────────────────────────────────────────────────────────────
# Раскраска включается ТОЛЬКО когда её есть кому показать. Раньше коды уходили
# всегда, и `goamnezia > отчёт.txt` давал файл, забитый \033[0;36m, а на
# терминале без цветов (TERM=dumb, вывод в конвейер, NO_COLOR у человека) экраны
# читались как мусор. Правила, в порядке проверки:
#   • GOAMNEZIA_COLOR=always|never — явная воля вызывающего, сильнее всего;
#   • NO_COLOR любой непустой... — по no-color.org достаточно самого наличия
#     переменной, поэтому проверяем объявлена ли она, а не её значение;
#   • TERM пуст или dumb — терминал не умеет ANSI;
#   • stdout не терминал — вывод идёт в файл, в конвейер или в JSON моста.
# Решение принимается один раз при подключении модуля: пересчитывать его на
# каждую строку экрана незачем, а тесты подменяют переменные окружения до вызова.
ga_color_enabled() {
    case "${GOAMNEZIA_COLOR:-auto}" in
        always|1|yes) return 0 ;;
        never|0|no)   return 1 ;;
    esac
    [ -z "${NO_COLOR+x}" ] || return 1
    case "${TERM:-}" in ""|dumb) return 1 ;; esac
    [ -t 1 ]
}

if ga_color_enabled; then
    RED='\033[0;31m'
    GREEN='\033[0;32m'
    CYAN='\033[0;36m'
    YELLOW='\033[1;33m'
    MAGENTA='\033[0;35m'
    BLUE='\033[0;34m'
    WHITE='\033[1;37m'
    BOLD='\033[1m'
    DIM='\033[2m'
    NC='\033[0m'
else
    RED=''; GREEN=''; CYAN=''; YELLOW=''; MAGENTA=''; BLUE=''
    WHITE=''; BOLD=''; DIM=''; NC=''
fi

# ── Размеры экрана ────────────────────────────────────────────────────────────
# Одна ширина на весь продукт (замечание критика: три соседних экрана были 56,
# 74 и 93 колонки, и два не помещались в стандартное окно 80×24). 76 — это
# 2 пробела отступа + 76 = 78 колонок, то есть с запасом в любом окне 80.
# Ширина текстовой колонки. Раньше здесь стояла жёсткая 76 независимо от окна, и
# на узком терминале (телефон, разделённый экран, ssh из редактора) переносы
# считались по 76, а рисовалось в 60 — текст вылезал за край и рамка ломалась.
# Теперь значение следует окну и обновляется на каждой отрисовке экрана:
# ga_ui_refresh_width ниже, вызов — из ga_clear_screen.
GA_UI_W="${GOAMNEZIA_UI_WIDTH:-76}"

# Реальные размеры окна. tput спрашиваем один раз за вызов и только когда есть
# терминал: на конвейере он отвечает по TERM и врёт. Порядок — как у всех
# терминальных программ: COLUMNS/LINES (их держит сама оболочка) → tput →
# безопасное умолчание 80×24.
ga_term_cols() {
    local n=""
    if [ -t 1 ] || [ -t 2 ]; then
        n="${COLUMNS:-}"
        [ -n "$n" ] || n=$(tput cols 2>/dev/null) || n=""
    else
        n="${COLUMNS:-}"
    fi
    [[ "$n" =~ ^[0-9]+$ ]] && [ "$n" -gt 0 ] || n=80
    printf '%s' "$n"
}
# Пересчитать GA_UI_W по реальному окну. Явно заданная GOAMNEZIA_UI_WIDTH
# главнее: ею пользуются проверки и тот, кто хочет фиксированную ширину.
# Четыре колонки оставляем на поля, 76 — потолок (длинная строка неудобна для
# чтения), 36 — пол: уже этого рисовать нечего, пусть лучше вылезет, чем
# превратится в лестницу из одного слова.
ga_ui_refresh_width() {
    local cols
    if [ -n "${GOAMNEZIA_UI_WIDTH:-}" ]; then GA_UI_W="$GOAMNEZIA_UI_WIDTH"; return 0; fi
    cols=$(ga_term_cols)
    # Настоящая ширина окна — для таблиц шире GA_UI_W (адреса сервера в шапке): узкое окно SSH с телефона
    # иначе от широкого не отличить, GA_UI_W упирается в потолок 76.
    GA_TERM_COLS="$cols"
    GA_UI_W=$(( cols - 4 ))
    [ "$GA_UI_W" -gt 76 ] && GA_UI_W=76
    [ "$GA_UI_W" -lt 36 ] && GA_UI_W=36
    return 0
}

ga_term_lines() {
    local n=""
    if [ -t 1 ] || [ -t 2 ]; then
        n="${LINES:-}"
        [ -n "$n" ] || n=$(tput lines 2>/dev/null) || n=""
    else
        n="${LINES:-}"
    fi
    [[ "$n" =~ ^[0-9]+$ ]] && [ "$n" -gt 0 ] || n=24
    printf '%s' "$n"
}

# Очистка экрана БЕЗ истории прокрутки. `clear` на большинстве систем шлёт ещё и
# E3 (\033[3J), а он выбрасывает скроллбэк — вместе с ним со страницы исчезал
# только что показанный ключ первого пользователя, и вернуть его было нечем.
# \033[H — курсор в левый верхний угол, \033[2J — очистить видимый экран.
ga_clear_screen() {
    # Размер окна мог измениться между экранами: человек развернул терминал или
    # повернул телефон. Обновляем до проверки цвета — ширина нужна и там, где
    # раскраска выключена.
    ga_ui_refresh_width
    ga_color_enabled || { printf '\n'; return 0; }
    printf '\033[H\033[2J'
}

# Дни вместе со словом: 1 → «1 день», 2 → «2 дня», 5 → «5 дней»; в en — «1 day»
# и «5 days». Без этого продукт печатал человеку «продлить на 1 дней»: внутри
# строки словаря склонять нечем, поэтому число и слово приходят в неё ОДНИМ
# аргументом.
#
# Сами слова — в словаре (lib/lang/<язык>.sh), и ПРАВИЛО выбора тоже: его
# называет ключ days_rule своего языка. Правила у языков разные, и общего
# «по последней цифре» не хватает: по-русски 21 — «день», по-английски 21 — уже
# «days». Правило в словаре, а не в этом коде, чтобы автор нового языкового
# фрагмента задавал его сам, не трогая модуль; неизвестное правило (и пропавший
# ключ) считаем английским — оно портит только «21 день», а не весь текст.
#
# Две последние цифры смотрим строкой, а не остатком от деления: в сообщение об
# ошибке попадает то, что ввёл человек, а «99999999999999999999» в арифметике
# bash — не число, а падение прямо посреди текста ошибки. По той же причине
# нечисло (agents_extend зовёт с «-») возвращаем как есть.
ga_days() {
    local n="${1:-0}" pad bare last two
    [[ "$n" =~ ^[0-9]+$ ]] || { printf '%s' "$n"; return 0; }
    # Два нуля впереди — чтобы «5» осталось «5»: у ${n: -2} на строке короче
    # двух знаков результат ПУСТОЙ, и день превращался в арифметическую ошибку.
    pad="00$n"
    two=$(( 10#${pad: -2} )); last=$(( 10#${pad: -1} ))
    if [ "$(t days_rule)" = last-digit ]; then
        # Русское правило: 1, 21, 31 — «день»; 2–4, 22–24 — «дня»; остальные —
        # «дней», и 11–14 тоже, хотя кончаются на 1–4.
        if [ "$two" -ge 11 ] && [ "$two" -le 14 ]; then tf days_many "$n"
        elif [ "$last" -eq 1 ]; then tf days_one "$n"
        elif [ "$last" -ge 2 ] && [ "$last" -le 4 ]; then tf days_few "$n"
        else tf days_many "$n"
        fi
        return 0
    fi
    # Английское правило: единственное число ровно у одного дня. Ведущие нули
    # снимаем сами: «01» — тот же один день, а не «01 days».
    bare="$n"
    while [ "${#bare}" -gt 1 ] && [ "${bare#0}" != "$bare" ]; do bare="${bare#0}"; done
    if [ "$bare" = 1 ]; then tf days_one "$n"; else tf days_many "$n"; fi
}

# ga_human_ts <ISO-8601 UTC> → «через 23 ч (2026-09-29 02:17 по времени сервера)» или «2 ч назад (…)» для экрана.
#
# Внутри продукта время хранится в ISO-8601 («2026-09-12T17:34:03Z») — это
# обмен между машинами, и таким оно и должно оставаться в JSON. А на экране
# человек спотыкается: «T» между датой и временем, «Z» в хвосте и секунды,
# которые ему не нужны. Сначала — сколько осталось или прошло, в скобках — время на часах сервера с пометкой:
# часы сервера обычно идут по UTC, и голое «23:06 UTC» человек в Москве читал как «ещё три часа» (находка NC-11
# критика-новичка). Не ISO или не разобралось — прежний вид без пересчёта: пусть лучше видно как есть, чем
# потеряется.
ga_human_ts() {
    local iso="${1:-}" day rest e abs
    [ -n "$iso" ] || { printf '%s' '-'; return 0; }
    case "$iso" in
        *T*) ;;
        *) printf '%s' "$iso"; return 0 ;;
    esac
    if e=$(ga_iso_epoch "$iso"); then
        abs=$(date -d "@$e" '+%Y-%m-%d %H:%M' 2>/dev/null || date -r "$e" '+%Y-%m-%d %H:%M' 2>/dev/null) || abs=""
        if [ -n "$abs" ]; then
            printf '%s (%s)' "$(ga_rel_time "$e")" "$(tf ts_server_clock "$abs")"
            return 0
        fi
    fi
    day="${iso%%T*}"
    rest="${iso#*T}"
    rest="${rest%Z}"
    rest="${rest%%+*}"
    # Секунды человеку не нужны: «14:53:08» он читает как «14:53».
    case "$rest" in *:*:*) rest="${rest%:*}" ;; esac
    printf '%s %s UTC' "$day" "$rest"
}

# ga_iso_epoch <ISO-8601 UTC> → секунды с 1970 года. «Z», доли секунды и «+00:00» снимаются, время без секунд тоже
# годится; прочее (и чужой часовой пояс) — rc 1. GNU date и BSD date.
ga_iso_epoch() {
    local s="${1:-}" e=""
    s="${s%Z}"; s="${s%+00:00}"; s="${s%%.*}"
    [[ "$s" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}(:[0-9]{2})?$ ]] || return 1
    [[ "$s" =~ T[0-9]{2}:[0-9]{2}$ ]] && s="${s}:00"
    e=$(date -u -d "${s/T/ }" +%s 2>/dev/null) || e=$(date -u -j -f '%Y-%m-%dT%H:%M:%S' "$s" +%s 2>/dev/null) || e=""
    [[ "$e" =~ ^[0-9]+$ ]] || return 1
    printf '%s' "$e"
}

# ga_rel_time <секунды с 1970> → «через 5 минут», «через 24 ч», «через 3 дн.» или «5 минут назад», «2 ч назад»,
# «3 дн. назад». До часа — минутами словами, до двух суток — часами, дальше — днями.
ga_rel_time() {
    local e="${1:-0}" now d a unit
    now=$(date +%s)
    d=$(( e - now )); a=${d#-}
    if [ "$a" -lt 3600 ]; then
        a=$(( (a + 30) / 60 )); [ "$a" -ge 1 ] || a=1
        unit=$(ga_minutes "$a")
    elif [ "$a" -lt 172800 ]; then
        unit=$(tf ts_hours $(( (a + 1800) / 3600 )))
    else
        unit=$(tf ts_days $(( (a + 43200) / 86400 )))
    fi
    if [ "$d" -ge 0 ]; then tf ts_in "$unit"; else tf ts_ago "$unit"; fi
}

# ga_minutes <n> → «5 минут» / «1 минуту» / «2 минуты» (EN — «5 minutes»): склонение по правилу языка, как у дней.
ga_minutes() {
    local n="${1:-0}" two last
    [[ "$n" =~ ^[0-9]+$ ]] || { printf '%s' "$n"; return 0; }
    two=$(( 10#$n % 100 )); last=$(( 10#$n % 10 ))
    if [ "$(t days_rule)" = last-digit ]; then
        if [ "$two" -ge 11 ] && [ "$two" -le 14 ]; then tf minutes_many "$n"
        elif [ "$last" -eq 1 ]; then tf minutes_one "$n"
        elif [ "$last" -ge 2 ] && [ "$last" -le 4 ]; then tf minutes_few "$n"
        else tf minutes_many "$n"
        fi
        return 0
    fi
    if [ "$((10#$n))" = 1 ]; then tf minutes_one "$n"; else tf minutes_many "$n"; fi
}

# ga_cell <текст> <ширина> — ячейка таблицы ровно в ширину: длинное обрезаем с
# многоточием, короткое добиваем пробелами.
#
# Почему не «%-26.26s» у printf: точность там считается в БАЙТАХ. Русская метка
# из 26 знаков — это 52 байта, printf резал её посередине на тринадцати знаках,
# и вся правая часть строки уезжала влево. Добивку меряем ga_str_width — в
# колонках, а не в знаках: значок в метке занимает две колонки.
ga_cell() {
    local s="${1:-}" w="${2:-0}" n
    [[ "$w" =~ ^[0-9]+$ ]] && [ "$w" -gt 1 ] || { printf '%s' "$s"; return 0; }
    # Символы, а не байты, при любой локали: в локали C ${#s} и ${s:0:n} считали байты, и русская подпись
    # обрезалась вдвое раньше, а то и посреди буквы (L1-15 / TAIL-8).
    [ "$(ga_char_len "$s")" -gt "$w" ] && s="$(ga_char_cut "$s" $(( w - 1 )))…"
    n=$(( w - $(ga_str_width "$s") )); [ "$n" -lt 0 ] && n=0
    printf '%s%*s' "$s" "$n" ''
}

# ── Перенос по словам ─────────────────────────────────────────────────────────
# ga_wrap <текст> [ширина] [отступ продолжения] — печатает текст строками не
# длиннее ширины, разрывая по пробелам; вторая и следующие строки получают
# висячий отступ. Ширина считается ga_str_width (колонки, а не байты), поэтому
# русский текст не уезжает. Слово длиннее строки не режется: разорванный
# посередине ключ или URL человек уже не скопирует — пусть лучше вылезет.
ga_wrap() {
    local text="${1:-}" width="${2:-$GA_UI_W}" hang="${3:-0}" word line="" out="" pad=""
    [[ "$width" =~ ^[0-9]+$ ]] && [ "$width" -gt 8 ] || width=76
    [[ "$hang" =~ ^[0-9]+$ ]] || hang=0
    [ "$hang" -gt 0 ] && printf -v pad '%*s' "$hang" ''
    for word in $text; do
        if [ -z "$line" ]; then
            line="$word"
        elif [ "$(ga_str_width "$line $word")" -le "$width" ]; then
            line="$line $word"
        else
            out="${out}${line}"$'\n'
            line="${pad}${word}"
        fi
    done
    out="${out}${line}"
    printf '%s' "$out"
}

# ga_win_wrap <текст> [отступ] — перенос по ширине НАСТОЯЩЕГО окна и только на
# терминале. На широком окне строка остаётся как была; в файл, в журнал и в
# мост она идёт целой — там её ищут и разбирают. Ширина — от окна, а не от
# GA_UI_W: задача здесь не читаемость (у неё свой потолок 76), а «не вылезти
# за край» — на ширине 60 за край вылезали десятки строк (DEFECTS §2.5).
ga_win_wrap() {
    local text="${1:-}" indent="${2:-2}" cols w ln fits=1
    [ -t 2 ] || { printf '%s' "$text"; return 0; }
    cols=$(ga_term_cols)
    w=$(( cols - indent - 1 ))
    [ "$w" -ge 20 ] || { printf '%s' "$text"; return 0; }
    [ "$(ga_str_width "$text")" -le "$w" ] && { printf '%s' "$text"; return 0; }
    # Уже перенесённый текст (_ui_w — по 76) оставляем как есть, если в окно влезает КАЖДАЯ его строка: раньше строки
    # склеивались заново по ширине окна, и на широком окне абзац ⚠ шёл на всю ширину, а «Кому что сделать» — по 76
    # (LH-4). Если не влезает хоть одна — переносим весь текст заново, как прежде: построчный перенос рвал каждую
    # строку на кусок и хвост («гребёнка») и терял отступ строк продолжения (NB2-1).
    if [[ "$text" == *$'\n'* ]]; then
        while IFS= read -r ln || [ -n "$ln" ]; do
            [ "$(ga_str_width "$ln")" -le "$w" ] || { fits=0; break; }
        done <<<"$text"
        [ "$fits" = 1 ] && { printf '%s' "$text"; return 0; }
    fi
    ga_wrap "$text" "$w" "$indent"
}

# ── Заглушки t/tf ─────────────────────────────────────────────────────────────
# common.sh сорсится раньше i18n.sh, а функции ниже зовут t/tf. Определяем
# заглушки ТОЛЬКО если настоящих ещё нет: после source lib/i18n.sh настоящие
# перекроют эти. Заглушка печатает сам ключ — ровно так же ведёт себя t()
# при промахе, поэтому поведение предсказуемо и без словаря.
if ! type t >/dev/null 2>&1; then
    t() { printf '%s\n' "${1:-}"; }
fi
if ! type tf >/dev/null 2>&1; then
    tf() { local k="${1:-}"; shift; printf '%s %s\n' "$k" "$*"; }
fi

# ── Логирование (всё в stderr: stdout занят результатами функций) ─────────────
# Перенос внутри самих помощников, а не у каждого вызова: длинная строка на
# узком окне вылезала за край на любом из сотен мест (DEFECTS §2.5). Продолжение
# встаёт под текст, а не под значок.
log_info()    { echo -e "  ${CYAN}ℹ${NC} $(ga_win_wrap "$*" 4)" >&2; }
log_success() { echo -e "  ${GREEN}✓${NC} $(ga_win_wrap "$*" 4)" >&2; }
log_warning() { echo -e "  ${YELLOW}⚠${NC} $(ga_win_wrap "$*" 4)" >&2; }
log_error()   { echo -e "  ${RED}✗${NC} $(ga_win_wrap "$*" 4)" >&2; }
log_step()    { echo -e "\n${BOLD}${WHITE}  $*${NC}" >&2; }
log_dim()     { echo -e "  ${DIM}$(ga_win_wrap "$*" 2)${NC}" >&2; }

# Скобки вокруг всей конструкции, а не «2>/dev/null» у echo: неудачу самого
# ПЕРЕНАПРАВЛЕНИЯ печатает оболочка, и подавление у команды её не гасит. Без
# скобок каждая запись в недоступный журнал (запуск не от root, прогон тестов)
# выплёвывала человеку сырую строку «Permission denied» посреди экрана.
log_to_file() {
    local ts; ts=$(date '+%Y-%m-%d %H:%M:%S')
    { echo "[$ts] $*" >> "$LOG_FILE"; } 2>/dev/null || true
}

# ── Время в ISO-8601 UTC ──────────────────────────────────────────────────────
# Один формат на весь продукт: config.json, users.json, clientsTable контейнера
# и аудит. `date -Iseconds` отдаёт локальную зону со смещением, а приложение
# Amnezia в clientsTable ожидает читаемую метку — держим UTC с Z.
ga_now() { date -u +%Y-%m-%dT%H:%M:%SZ; }

# ── Спиннер ───────────────────────────────────────────────────────────────────
_spin_pid=""
# spinner_start <сообщение> [ожидаемое время]
# Кроме бегущего значка показывает СЕКУНДЫ с начала шага: установка Docker и
# загрузка образа идут минутами, и без счётчика экран выглядел зависшим —
# анимация одна этого не снимала («минуты молчащей точки», замечание критика).
# Ожидаемое время (строка вроде «обычно 1–3 мин») печатается рядом, если задано.
# Без терминала (конвейер, `curl | bash`) анимации нет вовсе: там \r превращает
# лог в кашу — печатаем одну строку и молчим.
spinner_start() {
    local msg="${1:-$(t wait)}" eta="${2:-}"
    if [ ! -t 2 ]; then
        echo -e "  ${CYAN}·${NC} ${msg}${eta:+ ${DIM}(${eta})${NC}}" >&2
        _spin_pid=""
        return 0
    fi
    # Строка значка обязана помещаться в окно: перерисовка идёт через \r, а он
    # возвращает курсор лишь в начало ПОСЛЕДНЕЙ экранной строки, и длинная
    # строка оставляла хвосты на каждом кадре. Сначала жертвуем пояснением к
    # сроку, потом обрезаем само сообщение (DEFECTS §2.5).
    local cols room
    cols=$(ga_term_cols)
    room=$(( cols - 4 - 10 ))
    if [ -n "$eta" ] && [ "$(ga_str_width "$msg, $eta")" -gt "$room" ]; then eta=""; fi
    if [ "$room" -gt 12 ] && [ "$(ga_str_width "$msg")" -gt "$room" ]; then
        msg="${msg:0:$(( room - 1 ))}…"
    fi
    (
        local frames=('⠋' '⠙' '⠹' '⠸' '⠼' '⠴' '⠦' '⠧' '⠇' '⠏')
        local i=0 ticks=0 secs el fmt="${I18N[spinner_elapsed]:-%s}"
        while true; do
            secs=$(( ticks / 10 ))
            # printf -v, а не $(tf …): подстановка — дочерний процесс, и значок,
            # остановленный посреди кадра, оставлял его писать в закрытый канал.
            # Человек видел посреди мастера сырое «printf: write error: Broken
            # pipe» (DEFECTS §2.5).
            # shellcheck disable=SC2059
            printf -v el "$fmt" "$secs"
            printf "\r\033[K  ${CYAN}${frames[$i]}${NC} ${msg} ${DIM}%s%s${NC}" \
                "$el" "${eta:+, $eta}" >&2
            i=$(( (i+1) % ${#frames[@]} ))
            ticks=$(( ticks + 1 ))
            sleep 0.1
        done
    ) &
    _spin_pid=$!
}

spinner_stop() {
    [ -n "$_spin_pid" ] && kill "$_spin_pid" 2>/dev/null && wait "$_spin_pid" 2>/dev/null
    _spin_pid=""
    printf "\r\033[K" >&2
}

# ── Прогресс-бар ──────────────────────────────────────────────────────────────
progress_bar() {
    local current="$1" total="$2" label="${3:-}"
    [ "${total:-0}" -gt 0 ] 2>/dev/null || total=1
    local pct=$(( current * 100 / total ))
    local filled=$(( pct / 2 ))
    local empty=$(( 50 - filled ))
    local bar="" i
    for ((i=0; i<filled; i++)); do bar+="█"; done
    for ((i=0; i<empty; i++)); do bar+="░"; done
    printf "\r  ${GREEN}[${bar}]${NC} ${pct}%% ${label}" >&2
    [ "$current" -ge "$total" ] && echo "" >&2
    return 0
}

# ── Выполнение с индикатором ──────────────────────────────────────────────────
run_with_spinner() {
    local label="$1"; shift
    ga_step "$label" "" "" "$@"
}

# ── Шаг с индикатором, номером и результатом ──────────────────────────────────
# ga_step <подпись> <подпись результата> <ожидаемое время> <команда…>
#
# Два текста вместо одного — замечание критика: спиннер объявлял успех в
# настоящем времени («✓ Ставлю Docker»), хотя ставить уже закончил. Теперь пока
# идёт — «Ставлю Docker», после — «Docker установлен». Пустая вторая подпись
# оставляет прежнее поведение (её берут вызовы, где текст и так нейтрален).
#
# Номер шага — из GA_STEP_N (сколько всего) и внутреннего счётчика: длинные
# сценарии вроде мастера установки перестают быть чередой одинаковых точек.
# GA_STEP_N=0 (по умолчанию) — нумерации нет.
GA_STEP_N=0
GA_STEP_I=0
# ga_step_done <строка> — отметить сделанным шаг, который делали НЕ через
# ga_step (например `systemctl restart`, где спиннер не нужен). Счётчик шагов
# один на всё действие: без этого «Шаг 2 из 6» останавливался на двух, а
# остальное шло без номеров (DEFECTS §4.2).
ga_step_done() {
    local label="${1:-}"
    if [ "${GA_STEP_N:-0}" -gt 0 ] 2>/dev/null; then
        GA_STEP_I=$(( GA_STEP_I + 1 ))
        label="$(tf step_counter "$GA_STEP_I" "$GA_STEP_N") ${label}"
    fi
    log_success "$label"
}

ga_step() {
    local label="$1" done_label="${2:-}" eta="${3:-}"; shift 3
    local shown="$label"
    if [ "${GA_STEP_N:-0}" -gt 0 ] 2>/dev/null; then
        GA_STEP_I=$(( GA_STEP_I + 1 ))
        shown="$(tf step_counter "$GA_STEP_I" "$GA_STEP_N") ${label}"
    fi
    # mktemp, а не предсказуемый /tmp/.goamnezia_spinner_err_$$: иначе локальный
    # непривилегированный пользователь подкладывает симлинк, и root пишет по нему.
    local err_file
    err_file=$(mktemp "${TMPDIR:-/tmp}/.goamnezia_spinner_err.XXXXXXXX" 2>/dev/null) || err_file="/dev/null"
    spinner_start "$shown" "$eta"
    "$@" >/dev/null 2>"$err_file"
    local rc=$?
    spinner_stop
    if [ $rc -eq 0 ]; then
        log_success "${done_label:-$shown}"
    else
        log_error "$shown ${RED}($(t error), $(t code): $rc)${NC}"
        # GA_STEP_NO_ERRHEAD — вызывающий сам скажет итог отказа целиком (GA_ERR_MSG): первые строки stderr тогда не
        # печатаем, иначе то же сообщение выходит дважды (перестановка линии, DUP-LINE-01).
        if [ -s "$err_file" ] && ! { [ -n "${GA_STEP_NO_ERRHEAD:-}" ] && [ -n "${GA_ERR_MSG:-}" ]; }; then
            log_dim "  $(head -3 "$err_file")"
        fi
    fi
    rm -f "$err_file"
    return $rc
}

# ── Длина строки в символах при любой локали ──────────────────────────────────
# Службы (бот, панель, страницы, таймеры) зовут мост без LANG, и в локали C bash считает БАЙТЫ: подпись из
# 30 русских букв (57 байт) отвергалась «недопустимым значением» и проверкой шаблона {1,48}, и проверкой
# длины модуля, а из SSH (UTF-8) те же 30 букв проходили (находка SR-23). C.UTF-8 — те же правила сравнения
# и диапазонов, что у C, только символ считается символом. Нет такой локали (очень старый glibc) — остаётся
# прежний счёт. Вся локаль процесса не меняется нарочно: grep в UTF-8 объявляет «бинарным» ввод с
# неверными байтами, а мост читает и чужие журналы, и вывод docker.
GA_UTF8_LC=""
_GA_UTF8_LC_DONE=""
ga_utf8_lc_init() {
    [ -z "$_GA_UTF8_LC_DONE" ] || return 0
    _GA_UTF8_LC_DONE=1
    local probe='я'
    if ( LC_ALL=C.UTF-8; [ "${#probe}" = 1 ] ) 2>/dev/null; then
        GA_UTF8_LC=C.UTF-8
    fi
    return 0
}
# ga_char_len <строка> → число символов UTF-8, а не байтов, при ЛЮБОЙ локали процесса. В локали C снимаем байты
# продолжения (0x80–0xBF) и считаем оставшиеся: у каждого символа ровно один начальный байт. Прежде счёт держался
# на C.UTF-8, а её нет на macOS и в урезанных образах — там подпись кириллицей снова считалась байтами и упиралась в
# предел вдвое раньше (находка L1-15 / TAIL-8).
ga_char_len() {
    local LC_ALL=C s="${1:-}"
    s="${s//[$'\x80'-$'\xbf']/}"
    printf '%s' "${#s}"
}

# ga_char_cut <строка> <n> → первые n символов UTF-8 при любой локали: ${s:0:n} в локали C режет байты и мог
# разрубить букву пополам (L1-15, ga_cell). Идём по байтам и останавливаемся перед началом (n+1)-го символа.
ga_char_cut() {
    local LC_ALL=C s="${1:-}" n="${2:-0}" i=0 c=0 len b
    [[ "$n" =~ ^[0-9]+$ ]] || n=0
    len=${#s}
    while [ "$i" -lt "$len" ]; do
        printf -v b '%d' "'${s:$i:1}"
        [ "$b" -lt 0 ] && b=$((b + 256))     # где char знаковый, старшие байты приходят отрицательными
        if [ "$b" -lt 128 ] || [ "$b" -ge 192 ]; then
            [ "$c" -eq "$n" ] && break
            c=$((c + 1))
        fi
        i=$((i + 1))
    done
    printf '%s' "${s:0:$i}"
}

# ── Видимая ширина строки ─────────────────────────────────────────────────────
# Рамка баннера сходилась только на английском: ширину считали как ${#s}, а
# `printf '%-Ns'` — и вовсе по БАЙТАМ, поэтому кириллица (2 байта на букву) и
# эмодзи (4 байта, 2 колонки) разъезжали правый край. Считаем колонки терминала
# честно и без внешних программ:
#   • LC_ALL=C внутри функции — bash начинает видеть БАЙТЫ, поэтому разбор UTF-8
#     не зависит от локали вызывающего (в C-локали ${#s} иначе врал бы вдвое);
#   • ANSI-последовательности ширины не имеют и снимаются заранее;
#   • комбинирующие знаки и селекторы начертания — 0 колонок;
#   • диапазоны CJK и эмодзи — 2 колонки (так их рисуют все живые терминалы).
ga_str_width() {
    local LC_ALL=C LANG=C
    local s="${1:-}" i=0 n b cp len w=0

    # Снять раскраску: \033[…m и прочие CSI. Через ${s//…} — sed в этой функции
    # звался бы на каждую строку рамки, а она рисуется на каждом экране.
    while [[ "$s" == *$'\033['* ]]; do
        local head="${s%%$'\033['*}" rest="${s#*$'\033['}"
        # отрезаем параметры CSI до финальной буквы
        while [ -n "$rest" ] && [[ "${rest:0:1}" == [0-9\;] ]]; do rest="${rest:1}"; done
        s="${head}${rest:1}"
    done

    n=${#s}
    while [ "$i" -lt "$n" ]; do
        printf -v b '%d' "'${s:$i:1}"
        if   [ "$b" -lt 128 ]; then len=1; cp=$b
        elif [ "$b" -lt 224 ]; then len=2; cp=$(( b & 31 ))
        elif [ "$b" -lt 240 ]; then len=3; cp=$(( b & 15 ))
        else                        len=4; cp=$(( b & 7 ))
        fi
        local k=1
        while [ "$k" -lt "$len" ] && [ $((i + k)) -lt "$n" ]; do
            printf -v b '%d' "'${s:$((i + k)):1}"
            cp=$(( (cp << 6) | (b & 63) ))
            k=$((k + 1))
        done
        i=$((i + len))
        # Нулевая ширина: комбинирующие знаки U+0300–036F, ZWJ, селекторы VS1–16
        if { [ "$cp" -ge 768 ] && [ "$cp" -le 879 ]; } || [ "$cp" -eq 8205 ] \
           || { [ "$cp" -ge 65024 ] && [ "$cp" -le 65039 ]; }; then
            :
        elif { [ "$cp" -ge 4352 ]   && [ "$cp" -le 4447 ]; }   ||   # хангыль-джамо
             { [ "$cp" -ge 8986 ]   && [ "$cp" -le 8987 ]; }   ||   # ⌚⌛
             { [ "$cp" -ge 9193 ]   && [ "$cp" -le 9203 ]; }   ||   # ⏩–⏳
             { [ "$cp" -ge 9725 ]   && [ "$cp" -le 9726 ]; }   ||
             { [ "$cp" -ge 9748 ]   && [ "$cp" -le 9749 ]; }   ||
             { [ "$cp" -ge 9800 ]   && [ "$cp" -le 9811 ]; }   ||   # зодиак
             { [ "$cp" -ge 9989 ]   && [ "$cp" -le 9989 ]; }   ||   # ✅
             { [ "$cp" -ge 10024 ]  && [ "$cp" -le 10024 ]; }  ||   # ✨
             { [ "$cp" -ge 11035 ]  && [ "$cp" -le 11036 ]; }  ||   # ⬛⬜
             { [ "$cp" -ge 11088 ]  && [ "$cp" -le 11088 ]; }  ||   # ⭐
             { [ "$cp" -ge 11093 ]  && [ "$cp" -le 11093 ]; }  ||   # ⭕
             { [ "$cp" -ge 11904 ]  && [ "$cp" -le 42191 ]; }  ||   # CJK и радикалы
             { [ "$cp" -ge 44032 ]  && [ "$cp" -le 55203 ]; }  ||   # хангыль
             { [ "$cp" -ge 63744 ]  && [ "$cp" -le 64255 ]; }  ||
             { [ "$cp" -ge 65281 ]  && [ "$cp" -le 65376 ]; }  ||   # полноширинные
             { [ "$cp" -ge 127744 ] && [ "$cp" -le 129791 ]; }; then   # эмодзи U+1F300–1FAFF
            w=$((w + 2))
        else
            w=$((w + 1))
        fi
    done
    printf '%s' "$w"
}

# ── Рамка ─────────────────────────────────────────────────────────────────────
# Одна строка рамки: «│ текст…добивка │». Текст приходит БЕЗ раскраски, цвет —
# отдельным аргументом: считать ширину проще, когда в строке нет ANSI, а
# ga_str_width всё равно их снимет, если они просочатся.
ga_box_row() {
    local text="${1:-}" inner="${2:-0}" color="${3:-}" pad w
    w=$(ga_str_width "$text")
    pad=$(( inner - w ))
    [ "$pad" -lt 0 ] && pad=0
    printf '%b│%b %b%s%b%*s %b│%b\n' "$CYAN" "$NC" "$color" "$text" "$NC" "$pad" '' "$CYAN" "$NC"
}

# Горизонталь рамки: <левый угол><повтор ─><правый угол>.
ga_box_rule() {
    local left="${1:-┌}" right="${2:-┐}" inner="${3:-0}" i out=""
    for ((i = 0; i < inner + 2; i++)); do out+="─"; done
    printf '%b%s%s%s%b\n' "$CYAN" "$left" "$out" "$right" "$NC"
}

# ── Баннер ────────────────────────────────────────────────────────────────────
# Рамка замкнутая: ширина считается по самой длинной строке В КОЛОНКАХ, а не по
# фиксированным 60 символам — русский подзаголовок длиннее и раньше вылезал за
# черту. Эмодзи внутри рамки нет намеренно: терминалы расходятся в том, рисовать
# ли «текстовые» символы вроде U+1F6E1 в одну колонку или в две, и любой такой
# знак снова сдвинул бы правый край у части людей.
show_banner() {
    local -a rows=() colors=() out=()
    local r line w inner=0 limit cols i
    rows+=("$(tf banner_title "$GOAMNEZIA_VERSION")");   colors+=("${BOLD}${WHITE}")
    rows+=("$(t banner_subtitle)");                      colors+=("$DIM")
    rows+=("$(t banner_features)");                      colors+=("$DIM")

    # Потолок внутренней ширины: на рамку и поля уходит четыре колонки. Без
    # этого длинная строка про совместимость делала рамку в 74 колонки, и на
    # окне в 60 весь баннер разваливался на лесенку — первое, что человек
    # видит при установке.
    ga_ui_refresh_width
    cols=$(ga_term_cols)
    limit=$(( cols - 4 ))
    [ "$limit" -lt 24 ] && limit=24

    # Длинные строки переносим по словам и показываем несколькими строками
    # рамки. Цвет наследуется от исходной строки, поэтому продолжение выглядит
    # её частью, а не новой записью.
    local -a texts=() tints=()
    for i in "${!rows[@]}"; do
        while IFS= read -r line; do
            [ -n "$line" ] || continue
            texts+=("$line"); tints+=("${colors[$i]}")
            w=$(ga_str_width "$line")
            [ "$w" -gt "$inner" ] && inner="$w"
        done <<< "$(ga_wrap "${rows[$i]}" "$limit" 0)"
    done
    [ "$inner" -gt 0 ] || inner="$limit"

    echo ""
    ga_box_rule "┌" "┐" "$inner"
