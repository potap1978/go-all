# ── Ожидание apt-лока и установка ─────────────────────────────────────────────
# На свежих Ubuntu/Debian unattended-upgrades держит dpkg lock первые минуты
# после загрузки → любой apt-get install падает с «Could not get lock».
# Ждём освобождения до 300 с, потом полагаемся на нативный DPkg::Lock::Timeout.
apt_lock_wait() {
    local max_wait="${1:-300}"
    local waited=0
    local warned=0
    while fuser /var/lib/dpkg/lock-frontend &>/dev/null \
          || fuser /var/lib/dpkg/lock &>/dev/null \
          || fuser /var/lib/apt/lists/lock &>/dev/null \
          || pgrep -f '^/usr/bin/unattended-upgrade' &>/dev/null; do
        if [ "$warned" = "0" ]; then
            log_warning "$(tf apt_locked "$max_wait")"
            warned=1
        fi
        sleep 3
        waited=$((waited + 3))
        if [ "$waited" -ge "$max_wait" ]; then
            ga_set_error apt_locked
            log_error "$(tf apt_lock_timeout "$max_wait")"
            log_dim "$(t apt_lock_hint)"
            return 1
        fi
    done
    [ "$warned" = "1" ] && log_success "$(tf apt_lock_released "$waited")"
    return 0
}

# apt_install <pkg> [pkg2 …] — ждёт lock, ставит пакеты; не вышло — обновляет списки пакетов и пробует
# ещё раз (как deps_install), при провале показывает хвост ошибки. На только что созданном сервере списков
# пакетов нет вовсе: Docker в Ленивом Pro после goInstaller падал «Unable to locate package docker.io» —
# живой прогон владельца 28.09.2026. Вывод apt — в файл, не на экран (NC-03); вопросов dpkg быть не должно.
# Запасной файл — /dev/null, и его удалять нельзя (см. deps_install).
apt_install() {
    [ $# -eq 0 ] && return 0
    apt_lock_wait || return 1
    export DEBIAN_FRONTEND=noninteractive
    local -a dpkg_opts=(-o Dpkg::Options::=--force-confdef -o Dpkg::Options::=--force-confold)
    local err_file; err_file=$(mktemp "${TMPDIR:-/tmp}/goamnezia_apt.XXXXXXXX" 2>/dev/null) || err_file="/dev/null"
    if ! apt-get -o DPkg::Lock::Timeout=120 install -y -qq "${dpkg_opts[@]}" "$@" >"$err_file" 2>&1 </dev/null; then
        log_dim "$(t deps_install_retry)"
        apt-get -o DPkg::Lock::Timeout=120 update -qq >/dev/null 2>&1 </dev/null || true
        if ! apt-get -o DPkg::Lock::Timeout=120 install -y -qq "${dpkg_opts[@]}" "$@" >"$err_file" 2>&1 </dev/null; then
            ga_set_error apt_install_failed
            log_error "$(tf apt_install_failed "$*")"
            [ -s "$err_file" ] && tail -n 5 "$err_file" | sed 's/^/    /' >&2
            [ "$err_file" = /dev/null ] || rm -f "$err_file"
            return 1
        fi
    fi
    [ "$err_file" = /dev/null ] || rm -f "$err_file"
    return 0
}

apt_update() {
    apt_lock_wait || return 1
    export DEBIAN_FRONTEND=noninteractive
    apt-get -o DPkg::Lock::Timeout=120 update -qq 2>/dev/null || true
    return 0
}

