# Быстрая проверка на старте меню: ничего не ставит, только смотрит.
# Дороже неё только apt-get update, а он на каждом запуске меню недопустим.
GA_CORE_COMMANDS="jq curl openssl tar flock ss dig python3"
check_deps_present() {
    local cmd
    # Когда модуль загружен, проверяем и версии: существующий старый jq не должен обходить доустановку.
    if type deps_check >/dev/null 2>&1; then
        # Отметка «core уже проверен, с тех пор ничего не менялось» (lib/deps.sh, deps_stamp_valid) — только там,
        # где её разрешил вызывающий: чтения моста и тики таймеров (install.sh, main). Меню, установка и изменения
        # проверяют полностью, и удачная полная проверка обновляет отметку.
        if [ "${GA_DEPS_STAMP:-0}" = 1 ] && type deps_stamp_valid >/dev/null 2>&1 && deps_stamp_valid core; then
            return 0
        fi
        DEPS_QUIET=1 deps_check core >/dev/null 2>&1 || return 1
        [ "${#DEPS_MISSING[@]}" = 0 ] || return 1
        type deps_stamp_write >/dev/null 2>&1 && deps_stamp_write core
        return 0
    fi
    for cmd in $GA_CORE_COMMANDS; do
        command -v "$cmd" &>/dev/null || return 1
    done
    return 0
}

# ga_df_mb [каталог] → «всего занято свободно процент» (МБ, процент со знаком %) для раздела каталога одной
# строкой; пусто — df не ответил. Все пороги места (check_disk_space, ga_disk_json, зеркало, журналы,
# «Диагностика») меряют через неё.
#
# GOAMNEZIA_DF_FIXTURE — сохранённый вывод `df -Pm` (заголовок и строка раздела), как GOAMNEZIA_SS_FIXTURE у ss:
# с ним диск машины не спрашивается вовсе. Пороги — константы продукта (1 ГБ под образ, 512 МБ под копию,
# 1 ГБ запаса зеркалу), и сухой прогон на маленьком /tmp или корне CI отказывал «мало места» там, где на
# сервере его хватает (TAIL-12): набор тестов задаёт фикстуру с запасом. Без фикстуры — df, как прежде;
# тесты «диск полон» подменяют df сами.
ga_df_mb() {
    local where="${1:-/}"
    if [ -n "${GOAMNEZIA_DF_FIXTURE:-}" ]; then
        awk 'NR == 2 {print $2, $3, $4, $5; exit}' "$GOAMNEZIA_DF_FIXTURE" 2>/dev/null
        return 0
    fi
    [ -d "$where" ] || where=/
    df -Pm "$where" 2>/dev/null | awk 'NR == 2 {print $2, $3, $4, $5}'
}

# check_disk_space <мегабайт> [куда] — хватает ли места ТАМ, КУДА ПИШЕМ.
#
# Второй аргумент появился не для красоты: раньше мерился всегда корень, а
# пишем мы в $GOAMNEZIA_DIR, который на сервере бывает отдельным разделом.
# Мерить не тот раздел — значит и отказывать не тогда, и пропускать тогда.
check_disk_space() {
    local min_mb="${1:-1024}" where="${2:-/}"
    local avail_mb
    [ -d "$where" ] || where="/"
    avail_mb=$(ga_df_mb "$where" | awk '{print $3}')
    [[ "${avail_mb:-}" =~ ^[0-9]+$ ]] || return 0
    if [ "$avail_mb" -lt "$min_mb" ]; then
        ga_set_error low_disk
        log_error "$(tf err_low_disk "$avail_mb" "$min_mb")"
        return 1
    fi
    return 0
}

# ── Место на диске для status и шапки меню (находка OPS-01) ──────────────────
# Раньше о заполненном диске говорила только «Диагностика». Пороги — те же, что у неё и у модулей: ниже
# GA_DISK_LOW_MB (1024 МБ — порог образа Amnezia, GA_AMN_MIN_DISK_MB) не пройдёт обновление ядра, ниже
# GA_DISK_CRITICAL_MB (512 МБ — порог плановой копии, GA_BACKUP_MIN_DISK_MB) не снимется и ночная копия.
GA_DISK_LOW_MB=1024
GA_DISK_CRITICAL_MB=512

# ga_disk_json [каталог] → {path, total_mb, used_mb, free_mb, used_pct, level, low_mb, critical_mb} для раздела,
# где лежит каталог (по умолчанию каталог продукта): level — ok | low | critical. df не ответил — null.
ga_disk_json() {
    local where="${1:-${GOAMNEZIA_DIR:-/opt/goamnezia}}" line total="" used="" free="" pct="" level=ok
    [ -d "$where" ] || where=/
    line=$(ga_df_mb "$where")
    read -r total used free pct <<<"$line"
    pct="${pct%\%}"
    if ! [[ "$total" =~ ^[0-9]+$ && "$used" =~ ^[0-9]+$ && "$free" =~ ^[0-9]+$ && "$pct" =~ ^[0-9]+$ ]]; then
        printf 'null'
        return 0
    fi
    if [ "$free" -lt "$GA_DISK_CRITICAL_MB" ]; then
        level=critical
    elif [ "$free" -lt "$GA_DISK_LOW_MB" ]; then
        level=low
    fi
    jq -cn --arg p "$where" --argjson t "$total" --argjson u "$used" --argjson f "$free" --argjson pct "$pct" \
        --arg l "$level" --argjson lo "$GA_DISK_LOW_MB" --argjson cr "$GA_DISK_CRITICAL_MB" \
        '{path: $p, total_mb: $t, used_mb: $u, free_mb: $f, used_pct: $pct, level: $l, low_mb: $lo, critical_mb: $cr}' \
        2>/dev/null || printf 'null'
}

# ga_disk_tick → {level, prev, notified} и событие disk_level боту — только при СМЕНЕ уровня: ok → low → critical и
# обратно в ok, без повтора на каждом тике (TAIL-19: о заполняющемся диске бот говорил, лишь когда владелец сам
# открывал главный экран). Зовёт его сторож (watch-tick, раз в 2 минуты). Память — в /run (LOCK_DIR/disk_level):
# после перезагрузки неснятая тревога напомнит о себе один раз; первый тик на здоровом диске молчит. Память
# пишется ДО отправки: не записалась — не шлём, иначе событие уходило бы каждые две минуты. df не ответил — null.
ga_disk_tick() {
    local js level prev="" f notified=false
    js=$(ga_disk_json)
    [ -n "$js" ] && [ "$js" != null ] || { printf 'null'; return 0; }
    level=$(jq -r '.level // ""' <<<"$js" 2>/dev/null)
    case "$level" in ok|low|critical) ;; *) printf 'null'; return 0 ;; esac
    f="${LOCK_DIR:-/run/goamnezia}/disk_level"
    [ -f "$f" ] && prev=$( { tr -cd 'a-z' <"$f"; } 2>/dev/null )
    case "$prev" in ok|low|critical) ;; *) prev="" ;; esac
    if [ "$prev" != "$level" ]; then
        if mkdir -p "$(dirname "$f")" 2>/dev/null && { printf '%s\n' "$level" >"$f"; } 2>/dev/null; then
            # Первый тик на здоровом диске (памяти нет) — не новость
            if [ -n "$prev" ] || [ "$level" != ok ]; then
                ga_notify disk_level "$(jq -c --arg prev "${prev:-ok}" \
                    '{level, prev: $prev, free_mb, total_mb, used_pct, path, low_mb, critical_mb}' <<<"$js")" \
                    && notified=true
            fi
        fi
    fi
    jq -cn --arg l "$level" --arg p "${prev:-}" --argjson n "$notified" '{level: $l, prev: $p, notified: $n}'
}

