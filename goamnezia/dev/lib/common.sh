# Экранирование строки для JSON — запасной путь на случай отсутствия jq.
_ga_jesc() {
    local s="${1:-}"
    s="${s//\\/\\\\}"
    s="${s//\"/\\\"}"
    s="${s//$'\n'/\\n}"
    s="${s//$'\r'/\\r}"
    s="${s//$'\t'/\\t}"
    printf '%s' "$s"
}

# _ga_write_json <файл> — читает JSON со stdin и кладёт в файл АТОМАРНО.
# Три обязательных свойства (все три оплачены авариями в goTelegram):
#   1) содержимое сначала проверяется через jq: обрезанный или пустой ввод не
#      должен затирать рабочий конфиг;
#   2) mktemp РЯДОМ с целью, а не в /tmp: mv атомарен только в пределах одной
#      ФС, иначе это копирование, и при ENOSPC остаётся обрезанный файл;
#   3) chmod 600 на временном файле ДО mv: иначе между mv и chmod существует
#      окно, в котором users.json с приватными ключами читается кем угодно.
_ga_write_json() {
    local target="${1:-}"
    [ -n "$target" ] || return 1
    # Снимок config.json этого процесса (ga_config_memo_load) после записи врал бы — выключаем до записи.
    [ "$target" = "$CONFIG_FILE" ] && GA_CFG_MEMO_ON=0
    command -v jq >/dev/null 2>&1 || { ga_set_error no_jq; log_error "$(t err_no_jq)"; return 1; }
    mkdir -p "$(dirname "$target")" 2>/dev/null || true
    local tmp
    tmp=$(mktemp "${target}.XXXXXX") || { ga_set_error tmp_failed; return 1; }
    chmod 600 "$tmp" 2>/dev/null || true
    if ! jq -S . > "$tmp" 2>/dev/null; then
        rm -f "$tmp"
        ga_set_error invalid_json
        log_error "$(tf err_invalid_json "$(basename "$target")")"
        return 1
    fi
    # Пустой файл после jq — тот же признак битого ввода
    if [ ! -s "$tmp" ]; then
        rm -f "$tmp"
        ga_set_error invalid_json
        log_error "$(tf err_invalid_json "$(basename "$target")")"
        return 1
    fi
    # 4) fsync файла, переименование, fsync каталога — иначе атомарность
    #    защищает только от других процессов, но не от пропажи питания: ядро
    #    вправе держать и содержимое временного файла, и запись каталога в
    #    кэше сколько угодно. Штатный итог внезапного выключения без этого —
    #    обрезанный users.json, то есть потеря приватных ключей всех
    #    пользователей. Договор (§3.1, §11.1) требует того же порядка, что уже
    #    сделан в хранилище цепочек агентов.
    _ga_commit_file "$tmp" "$target" || { rm -f "$tmp"; ga_set_error write_failed; return 1; }
    chmod 600 "$target" 2>/dev/null || true
    return 0
}

# _ga_commit_file <временный> <цель> — положить временный файл на место так,
# чтобы переживало выключение питания: fsync содержимого → rename → fsync
# каталога. Одним процессом python3, а не тремя вызовами: запуск интерпретатора
# стоит дороже самой работы, а запись состояния идёт на каждую мутацию.
#
# python3 нет (минимальный образ, ранняя стадия установки) — кладём обычным mv.
# Отказывать в записи из-за отсутствия синхронизатора нельзя: файл всё равно
# появится целиком, просто гарантия слабее. А вот ОШИБКА fsync при живом
# python3 — это отказ диска, и выдавать её за успех нельзя тем более.
_ga_commit_file() {
    local tmp="$1" target="$2"
    if ! command -v python3 >/dev/null 2>&1; then
        mv "$tmp" "$target" || return 1
        return 0
    fi
    python3 - "$tmp" "$target" <<'PY'
import os, sys
tmp, target = sys.argv[1], sys.argv[2]
try:
    fd = os.open(tmp, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)
    os.replace(tmp, target)
    # Без fsync каталога само ПОЯВЛЕНИЕ файла под новым именем может не пережить
    # выключение: данные легли, а запись каталога — нет.
    dfd = os.open(os.path.dirname(os.path.abspath(target)) or ".", os.O_RDONLY)
    try:
        os.fsync(dfd)
    finally:
        os.close(dfd)
except OSError:
    sys.exit(1)
PY
}

# ga_write_file <файл> <содержимое> [права] — небольшой служебный файл (язык, отметка миграции, «Что нового»)
# целиком или никак. Голое `printf >файл` сначала обрезает цель: кончилось место — файл остаётся пустым, а
# вызывающий с `|| true` рапортовал успех (находка OPS-04: при ENOSPC lang-set отвечал success, не записав
# config.json; на C1 так обнулилась отметка миграции). Здесь — времянка рядом с целью, запись со сверкой
# содержимого, fsync и rename (_ga_commit_file): прежний файл цел при любом отказе. Отказ — код 1,
# GA_ERR_CODE=write_failed и слова в GA_ERR_MSG; вызывающий обязан отдать их наружу, как users_write_failed.
ga_write_file() {
    local target="${1:-}" content="${2-}" mode="${3:-600}" tmp=""
    [ -n "$target" ] || return 1
    mkdir -p "$(dirname "$target")" 2>/dev/null || true
    if tmp=$(mktemp "${target}.XXXXXX" 2>/dev/null); then
        chmod "$mode" "$tmp" 2>/dev/null || true
        # Сверка прочитанного, а не код printf: обрезанная запись (место кончилось посреди файла) тоже отказ.
        if { printf '%s' "$content" >"$tmp"; } 2>/dev/null \
           && printf '%s' "$content" | cmp -s - "$tmp" \
           && _ga_commit_file "$tmp" "$target"; then
            return 0
        fi
        rm -f "$tmp" 2>/dev/null
    fi
    GA_ERR_CODE=write_failed
    if type tf >/dev/null 2>&1; then GA_ERR_MSG="$(tf ops_write_failed "$target")"; else GA_ERR_MSG="write failed: $target"; fi
    ga_set_error write_failed
    return 1
}

