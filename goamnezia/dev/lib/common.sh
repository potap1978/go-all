# ══════════════════════════════════════════════════════════════════════════════
#  Проверка значений, приходящих снаружи (контракт §0, правило 8)
# ══════════════════════════════════════════════════════════════════════════════
# Здесь лежат ЕДИНСТВЕННЫЕ проверки адреса, хоста и MTU на весь продукт. Своё
# регулярное выражение на каждый вызов — это проверка по ВИДУ, а не по значению:
# `^([0-9]{1,3}\.){3}[0-9]{1,3}$` радостно пропускает 999.999.999.999, и такой
# адрес доезжает до DNS в клиентском конфиге, где туннель просто не работает, а
# человек ищет причину в сервере. Любой модуль, который принимает адрес снаружи,
# обязан звать эти функции, а не сочинять регулярку заново.

# _valid_ip <строка> — IPv4 по ЗНАЧЕНИЮ октетов.
# Регулярка IPv4 по ЗНАЧЕНИЮ октетов — для тех мест, где нужна именно строка
# образца, а не функция: ga_ask и ga_ask_optional принимают регулярку. Везде,
# где можно позвать функцию, зовите _valid_ip: она одна, а копий образца
# расплодилось бы столько же, сколько экранов (§0.8 договора).
GA_RE_IPV4='^((25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])\.){3}(25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])$'

_valid_ip() {
    local ip="${1:-}"
    # Сначала форма: ровно четыре группы по одной–три цифры. Одним `read -ra` с
    # IFS='.' форму не поймать — хвостовую точку он молча съедает, и «1.2.3.4.»
    # проходило как адрес. Три цифры на группу заодно снимают вопрос
    # переполнения: без ограничения длины `[ "$octet" -gt 255 ]` считал бы
    # 20-значное число в 64-битной арифметике с переворотом знака.
    [[ "$ip" =~ ^[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}$ ]] || return 1
    local IFS='.'
    local octets octet
    read -ra octets <<< "$ip"
    for octet in "${octets[@]}"; do
        # Ведущий ноль запрещён: 010 одни библиотеки читают как 10, другие — как
        # восьмеричное 8, и «тот же» адрес у сервера и у клиента оказывается
        # разным. Однозначная запись дешевле разбирательства.
        [ "${#octet}" -gt 1 ] && [ "${octet:0:1}" = "0" ] && return 1
        [ "$octet" -gt 255 ] && return 1
    done
    return 0
}

# ga_valid_host <строка> — то, что годится в Endpoint ключа: имя узла ИЛИ IPv4.
# Имя узла — законный случай (Pro-режим выдаёт ключи на домен), поэтому здесь
# не просто _valid_ip: сначала решаем, что перед нами. Строка из одних цифр и
# точек — это попытка адреса, и она обязана пройти проверку по значению, а не
# уехать в «ну значит имя».
ga_valid_host() {
    local h="${1:-}"
    [ -n "$h" ] || return 1
    [ "${#h}" -le 253 ] || return 1
    if [[ "$h" =~ ^[0-9.]+$ ]]; then
        _valid_ip "$h"
        return $?
    fi
    # Имя узла: метки из букв, цифр и дефисов, дефис не с краю, минимум две
    # метки (одиночный `localhost` в Endpoint клиента бессмыслен).
    [[ "$h" =~ ^[a-z0-9]([-a-z0-9]*[a-z0-9])?(\.[a-z0-9]([-a-z0-9]*[a-z0-9])?)+$ ]]
}

# MTU клиентского конфига — один договор на весь продукт (docs/CONTRACT.md §4.3).
# Почему 1200–1500, а не «любое разумное число»: 1500 — MTU обычного Ethernet,
# выше него пакет всё равно фрагментируется по пути; ниже 1200 ломаются клиенты
# и часть сайтов по TLS. Диапазон 576–65535 из общей теории IP к туннелю
# AmneziaWG отношения не имеет, и раньше он же и расходился с этим договором:
# `profile-mtu 9000` отвергался, а `profile-set-param MTU 9000` проходил.
GA_MTU_MIN=1200
GA_MTU_MAX=1500
ga_valid_mtu() {
    local v="${1:-}"
    [[ "$v" =~ ^[0-9]{4}$ ]] || return 1
    [ "$v" -ge "$GA_MTU_MIN" ] && [ "$v" -le "$GA_MTU_MAX" ]
}

get_server_ip() {
    local ip raw url
    # Стенд и тесты: адрес задан снаружи (GOAMNEZIA_SERVER_IP, контракт §1) —
    # в сеть не ходим. Иначе dry-run на macOS и CI без интернета ждали бы
    # три таймаута curl на каждый status и на каждую выдачу ключа.
    if [ -n "${GOAMNEZIA_SERVER_IP:-}" ] && _valid_ip "${GOAMNEZIA_SERVER_IP}"; then
        echo "${GOAMNEZIA_SERVER_IP}"
        return 0
    fi
    for url in "https://api.ipify.org" "https://icanhazip.com" "https://ifconfig.me"; do
        raw=$(curl -s -4 --max-time 5 "$url" 2>/dev/null)
        ip=$(echo "$raw" | grep -Eo '([0-9]{1,3}\.){3}[0-9]{1,3}' | head -1)
        if [ -n "$ip" ] && _valid_ip "$ip"; then
            echo "$ip"
            return 0
        fi
    done
    echo "0.0.0.0"
    return 1
}

