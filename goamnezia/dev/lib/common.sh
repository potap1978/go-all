# ga_in_unit <юнит> — идёт ли текущий процесс внутри control group этого юнита systemd: мост позвала сама
# служба (бот, панель, HTTP-транспорт MCP), и остановка или перезапуск этой службы убили бы мост на полпути.
# Файл cgroup подменяется в проверках (GA_PROC_CGROUP); нет файла (не Linux) — не внутри.
ga_in_unit() {
    local unit="${1:-}" f="${GA_PROC_CGROUP:-/proc/self/cgroup}"
    [ -n "$unit" ] && [ -r "$f" ] || return 1
    unit="${unit%.service}.service"
    grep -qE "/${unit//./\\.}(/|$)" "$f" 2>/dev/null
}

# ga_timer_lock_wait → сколько секунд таймер ждёт общий замок (по умолчанию 120). Жалоба 29.09.2026: во время
# установки ночная копия (goamnezia-backup) и проверка сертификата (goamnezia-cert) ждали замок 30 с, получали
# lock_timeout и оставляли юнит в failed. Теперь таймер ждёт дольше, а замок так и не освободился — это «занято —
# пропущено, следующий запуск по таймеру» с кодом 0 (мост: action_dispatch, копия: backup_tick). Стенды ставят
# GOAMNEZIA_TIMER_LOCK_WAIT=1.
# Бюджет — один на весь тик: мост таймера ставит GA_TIMER_LOCK_DEADLINE (секунды эпохи) до ожидания замка миграцией,
# и дальше ответ — остаток до этого срока (0 — уже вышел: одна попытка без ожидания), а не новые 120 с.
ga_timer_lock_wait() {
    local w="${GOAMNEZIA_TIMER_LOCK_WAIT:-120}" left
    [[ "$w" =~ ^[0-9]{1,4}$ ]] || w=120
    w=$((10#$w))
    if [[ "${GA_TIMER_LOCK_DEADLINE:-}" =~ ^[0-9]{1,12}$ ]]; then
        left=$(( GA_TIMER_LOCK_DEADLINE - $(date +%s) ))
        [ "$left" -gt 0 ] || left=0
        [ "$left" -lt "$w" ] && w="$left"
    fi
    printf '%s' "$w"
}

# ══════════════════════════════════════════════════════════════════════════════
#  Единый замок (контракт §0.4)
# ══════════════════════════════════════════════════════════════════════════════
# В goTelegram замков было три, и они не пересекались: бот и панель брали один
# файл, мост --action свой, а SSH-меню не брало ничего. Параллельная запись из
# двух интерфейсов молча теряла ключи — в замере пропало 9 из 40. Здесь путь
# один на все интерфейсы: /run/goamnezia/config.lock.
ga_with_config_lock() {
    [ $# -gt 0 ] || return 0
    # Реентрантность: flock не рекурсивен. Вложенный вызов (ga_config_set внутри
    # users_add, который уже под замком) просто выполняет тело.
    if [ -n "${GA_CONFIG_LOCK_HELD:-}" ]; then "$@"; return $?; fi
    # Нет flock (busybox, стенд на macOS) — тело выполняем всё равно, но флаг
    # ставим: вложенные вызовы обязаны вести себя одинаково с замком и без него,
    # иначе проверка «мы внутри критической секции» врёт на половине систем.
    command -v flock >/dev/null 2>&1 || { GA_CONFIG_LOCK_HELD=1 "$@"; return $?; }
    mkdir -p "$(dirname "$LOCK_FILE")" 2>/dev/null || true
    # Динамический fd (bash 4.1+). Жёсткий `exec 9>` закрывал бы fd 9, на котором
    # внешний вызов уже держит flock, и молча снимал его замок.
    local _gafd
    # ВАЖНО: фигурные скобки обязательны. `exec {fd}>f 2>/dev/null` без
    # группировки вешает перенаправление stderr на ВСЮ оболочку до конца её
    # жизни — после первого взятия замка все log_error уходили в никуда, и
    # человек видел молчание вместо ошибки.
    { exec {_gafd}>"$LOCK_FILE"; } 2>/dev/null || { GA_CONFIG_LOCK_HELD=1 "$@"; return $?; }
    # GA_LOCK_WAIT — сколько ждать вместо 30 с: таймеру, который не торопится (ночная копия), установка или
    # обновление держат замок минутами, и он ждёт дольше, а не падает (lib/backup.sh backup_tick).
    local _gawait="${GA_LOCK_WAIT:-30}"
    [[ "$_gawait" =~ ^[0-9]{1,4}$ ]] || _gawait=30
    if ! flock -w "$_gawait" "$_gafd"; then
        # Контракт §0.4: 30 с и отказ с кодом lock_timeout (exit 75 делает
        # install.sh). goTelegram здесь ждал бесконечно — в интерактивном меню
        # это выглядит как зависание без объяснения, а мост --action вообще не
        # имеет права висеть: его зовут бот, панель и MCP с таймаутами.
        { exec {_gafd}>&-; } 2>/dev/null
        ga_set_error lock_timeout
        # GA_LOCK_QUIET=1 — вызывающий скажет сам (таймер: «занято — пропущено»), ошибка в журнале была бы враньём.
        [ "${GA_LOCK_QUIET:-0}" = 1 ] || log_error "$(t err_lock_timeout)"
        return 75
    fi
    local _rc=0
    GA_CONFIG_LOCK_HELD=1 "$@" || _rc=$?
    { exec {_gafd}>&-; } 2>/dev/null
    return $_rc
}

# ══════════════════════════════════════════════════════════════════════════════
#  Временные файлы с секретами (контракт §0, правило 7)
# ══════════════════════════════════════════════════════════════════════════════
# Через временные файлы продукта проходят вещи, которые нельзя оставлять на
# диске ни на секунду: готовый клиентский конфиг с приватным ключом, приватный
# ключ сервера, PNG с QR (это тот же ключ, только картинкой), содержимое
# users.json. Обычный mktemp кладёт их в общий каталог временных файлов, то
# есть на диск, а rm снимает только имя — содержимое остаётся в блоках до
# перезаписи и достаётся с носителя.
#
# Два правила, оба нужны:
#   • каталог по возможности В ПАМЯТИ (tmpfs): /dev/shm или /run/goamnezia —
#     там «файл» вообще не доезжает до носителя;
#   • перед удалением файл затирается нулями: на tmpfs это действительно
#     стирает содержимое, на обычной ФС — оставляет злоумышленнику меньше.
#     Для журналируемой ФС гарантии нет, поэтому первое правило важнее.

# ga_secret_tmpdir → каталог для временных файлов с секретами. Порядок:
# явное указание вызывающего → /dev/shm → каталог замков (на Linux это /run,
# тоже tmpfs) → общий временный каталог как последнее средство (стенд на macOS,
# где tmpfs нет вовсе).
ga_secret_tmpdir() {
    local d
    for d in "${GOAMNEZIA_SECRET_TMPDIR:-}" /dev/shm "${LOCK_DIR:-}"; do
        [ -n "$d" ] || continue
        [ -d "$d" ] && [ -w "$d" ] && { printf '%s' "$d"; return 0; }
    done
    printf '%s' "${TMPDIR:-/tmp}"
}

# ga_mktemp_secret [префикс] → путь нового временного файла 0600 в памяти.
ga_mktemp_secret() {
    local dir f
    dir=$(ga_secret_tmpdir)
    f=$(TMPDIR="$dir" mktemp "$dir/.${1:-goamnezia}.XXXXXXXX" 2>/dev/null) || return 1
    chmod 600 "$f" 2>/dev/null || true
    printf '%s' "$f"
}

# ga_mktemp_secret_dir [префикс] → путь нового временного КАТАЛОГА 0700 в
# памяти. Нужен там, где секрет не один файл, а целая распакованная россыпь:
# архив восстановления (users.json со всеми приватными ключами клиентов,
# приватный ключ сервера в state/, приватный ключ сертификата, .env с токеном
# бота). Обычный `mktemp -d` кладёт всё это в общий каталог временных файлов,
# то есть на диск и на виду; убирать такой каталог надо ga_wipe_dir.
ga_mktemp_secret_dir() {
    local dir d
    dir=$(ga_secret_tmpdir)
    d=$(TMPDIR="$dir" mktemp -d "$dir/.${1:-goamnezia}.XXXXXXXX" 2>/dev/null) || return 1
    chmod 700 "$d" 2>/dev/null || true
    printf '%s' "$d"
}

# ga_wipe_file <файл…> — затереть нулями и удалить. Размер берём у самого файла:
# записать нужно ровно столько, сколько было, иначе в хвосте останется прежнее.
ga_wipe_file() {
    local f size
    for f in "$@"; do
        [ -n "$f" ] || continue
        # Затираем только обычный файл: [ -f ] и запись идут по ссылке, и ссылка на чужой файл затёрла бы его
        # (Q-2). Саму ссылку просто убираем.
        if [ -f "$f" ] && [ ! -L "$f" ]; then
            # Скобки вокруг всей конструкции: неудачу ПЕРЕНАПРАВЛЕНИЯ печатает
            # оболочка, и «2>/dev/null» у команды её не гасит. Файл ключа может
            # исчезнуть между проверкой и затиранием — человек увидел бы сырую
            # строку «No such file or directory» посреди удаления профиля.
            size=$( { wc -c <"$f"; } 2>/dev/null | tr -d ' ')
            [[ "$size" =~ ^[0-9]+$ ]] && [ "$size" -gt 0 ] \
                && { head -c "$size" /dev/zero >"$f"; } 2>/dev/null
        fi
        rm -f "$f" 2>/dev/null || true
    done
    return 0
}

# ga_wipe_dir <каталог…> — то же для каталога целиком (QR-картинки, сборка).
ga_wipe_dir() {
    local d f
    for d in "$@"; do
        [ -n "$d" ] && [ -d "$d" ] || continue
        while IFS= read -r f; do
            [ -n "$f" ] && ga_wipe_file "$f"
        done < <(find "$d" -type f 2>/dev/null)
        rm -rf "$d" 2>/dev/null || true
    done
    return 0
}

