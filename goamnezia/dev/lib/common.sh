# get_arch — архитектура для образов Docker. Только x86_64.
# Почему только она: образы amneziawg-go, которые мы тянем по дайджесту,
# официально собираются только под linux/amd64 (PLAN §2.1).
# Молча собрать под arm64 значит выдать пользователю нерабочий контейнер и
# ловить это уже на клиенте — лучше отказать сразу и назвать код ошибки.
get_arch() {
    local arch
    arch=$(uname -m)
    case "$arch" in
        # На stdout — платформа в терминах Docker (linux/amd64), а не uname -m:
