# ── A day count together with its word (ga_days) ──
# The number and the word arrive as ONE argument: Russian declines the word
# after the number («1 день», «2 дня», «5 дней») and a dictionary string has
# no way to do that inside itself.
# days_rule names the plural rule of THIS language — it is never shown to
# anyone. English needs the plain one: singular for exactly one day, plural for
# everything else (21 is «21 days» here, while Russian says «21 день»), so the
